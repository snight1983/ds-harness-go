// Package sdkserver 是那条 SDK 协议的**服务端**这一半：把进程外 SDK 发过来的十三个
// 请求接住办掉，并且把这套运行时里的四类动静往回发。
//
// 源: packages/sdk/server/src/index.ts:1-10, packages/sdk/server/src/server.ts:1-6,
// packages/api/session-controller/src/session-controller.ts
//
// 线上说什么由 [github.com/snight1983/ds-harness-go/protocol/sdk/sdkprotocol] 定；本包只管**这一端怎么办事**。
//
// # 一台服务器管什么
//
// 三个请求是这条线本身的事：`initialize` 记下这条线上所有会话共用的那份路由（工作
// 目录、提供方、模型、可选的推理档位和输出上限），`session/prompt` 把一轮用户输入排
// 进某个会话（没见过的会话标识当场把 agent 和会话一起建出来；跟着请求内联送进来的
// 栅格图先走一次附件准入，落进会话日志的永远是那条引用而不是那些字节），`shutdown`
// 把这台服务器自己建出来的东西全部收掉。
//
// `initialize` 只有**整个走完**才算数：入参验完、适配器挂上或者确认过、那条路由真
// 解算过一遍，最后才公布。中间任何一步失败，这台服务器都还停在握手之前，客户端换
// 一份参数重来就是了；而握手之前进来的**任何**一个请求都一律被拒——那时的路由还是
// 空的，照它建出来的 agent 一步都跑不动。
//
// # 会话那十个方法各自转给谁
//
// 这十个方法自己不产生能力，是把运行时里已经有的那些挂上线：
//
//	方法                     真正干活的是
//	─────────────────────────────────────────────────────────────
//	session/create           agent 注册表（建）
//	session/resume           agent 注册表（按标识读回来）
//	session/fork             会话查询引擎 + agent 注册表（带种子建）
//	session/rename           装配方交进来的那个改名回调
//	session/list             会话查询引擎（冷读，含没活着的）
//	session/search           会话查询引擎背后那个检索后端
//	session/cancel           活 agent 自己的叫停
//	session/select-model     LLM 适配器解算 + 会话作用域上的那份模型选择
//	session/update-queue     活 agent 的收件箱
//	session/history          会话查询引擎（往老里翻页）
//
// 分成**活的**和**冷的**两路：改名、取消、换模型、改排队只对活着的会话办，会话不在
// 这条线上就当场拒，不隐式把它读回来——隐式读回会让一次拼错标识的取消悄悄启动一条
// 陈年会话。列举、检索、翻历史、分叉走冷读那一路，不要求会话活着。
//
// # 两处必须按下标而不是按 seq 算的地方
//
// 分叉找切点和翻历史切页都要在事件序列里定位。DSH 的日志从 0 起、只增不删，所以它
// 全程拿 seq 当下标使。这个仓库的会话日志有封顶，会从最老那头弹（见
// docs/session-log-limit.md），弹过之后 `events[0].Seq` 就不是 0 了。所以这两处都先取
// `base = events[0].Seq` 再换算——直接拿 seq 当下标，弹掉多少条就翻空多少条。
//
// 四类通知：会话日志事件、活 agent 的整体状态、运行时内部新开的子会话、以及一次
// 进程内子 agent 的结局。它们都是**转发**——这台服务器不生产任何事实，只是把运行
// 时已经在发的那些边翻成线上的话。
//
// # 它拥有什么、不拥有什么
//
// 它拥有**它自己建出来的那些 agent**，收摊时逐个拆掉。它不拥有运行时、不拥有那条
// 通道、也不拥有本进程——DSH 那边 `shutdown` 之后还要拆根上下文并且 `process.exit(0)`
// （sdk/server/src/index.ts:64-74），那两件事在 Go 这边留给装配方：它才是造出运行时
// 和通道的那一位，也只有它知道这个进程还有没有别的活儿。
//
// # 新增: 装配面为什么是显式字段而不是一个容器
//
// DSH 是一个 cordis 插件：`inject = ['agents']` 声明它要什么，`ctx.on(...)` 挂监听，
// `ctx.get('llm')` 探可选的服务。Go 没有那个容器，所以 agent 注册表、会话存储、子
// agent 运行时、以及那条通道的发送面，全部写在 [Config] 上由装配方交进来，缺一样
// 就在 [New] 当场拒——而不是等第一个请求进来才空指针。
//
// # 不做什么
//
//   - **不建 HTTP/WebSocket Listener，也不读进程的标准流。**那条通道由装配方造好
//     交进 [Config]，本包只在它上面收发。
//   - **不定线上说什么。**帧与形状归
//     [github.com/snight1983/ds-harness-go/protocol/sdk/sdkprotocol]，本包只管这一端
//     怎么办事。
//   - **不拥有运行时和本进程。**`shutdown` 只拆它自己建出来的那些 agent；拆根上下文
//     和退出进程留给装配方。
//   - **不生产任何事实。**四类通知全是转发，事实由运行时和
//     [github.com/snight1983/ds-harness-go/sessionlog] 那边产生。
//   - **不认证客户端，也不做租户隔离。**这条线默认已经是可信通道。
//   - **不自带会话持久化后端。**会话存储由装配方按
//     [github.com/snight1983/ds-harness-go/feature/persistence] 那道契约交进来。
//   - **不自带检索后端。**`session/search` 要求装配方给会话查询引擎挂一个检索实现，
//     没挂时那条路直接报「检索没开」，而不是降级成一次全表扫。
//   - **不隐式把会话读回来。**四个只对活会话办的方法碰到不在这条线上的标识就拒。
//   - **不把一次换模型记成部署的默认。**`session/select-model` 只改这一条会话，
//     DSH 那边跟着做的那次「记成下次的默认」不做——一条线上一个客户端换了模型，
//     不该让别的每一条会话下次都跟着变。
//   - **不做浏览器那一半。**增量订阅、流式 patch、重放游标都不落地；同一语义走
//     [github.com/snight1983/ds-harness-go/sessionlog/projection] 的整值投影。
