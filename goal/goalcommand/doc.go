// Package goalcommand 是 `/goal` 这条面向人的斜杠命令。
//
// 源: packages/goal/command-goal（@deepseek-ai/dsh-command-goal）
//
// # 它是什么
//
// 一层薄薄的适配：把人敲进编辑器的那一行字翻成
// [github.com/snight1983/ds-harness-go/goal/goal.Service] 上的一次调用，再把结果排成一段人读的文字。
// 它**不持有任何状态**——目标存在会话日志里，归那台目标服务管；这一层只负责
// 「这行字是什么意思」和「这个结果该怎么说」。
//
// 它认识的语法只有五条：空输入是看一眼、`clear`、`pause`、`resume`、
// `edit <新目标>`。除此之外的任何一行字都当成一个新目标——这是刻意的，因为人
// 敲 `/goal 把测试补齐` 的时候不该被要求先记住一个子命令表。
//
// # 和 [github.com/snight1983/ds-harness-go/goal/goaltool] 的分工
//
// 那一套是给**模型**的，这一套是给**人**的，两边故意不对称：
//
//   - 只有这一套有 `clear`。一个能自己清掉目标的模型等于一个没有预算的模型。
//   - 只有那一套有 `complete` 和 `block`。人不需要向自己报告进度。
//   - 这一套的每一条都当场生效并直接回话，不经过模型；那一套的每一条都是模型
//     在自己的回合里调的工具。
//
// # 图片附件
//
// 一次带图的 `/goal <目标>` 或 `/goal edit <目标>` 会把那些图作为一条普通的用户
// 消息发进会话，跟一句写明它们身份的文字。目标那一层因此**不必**存任何附件状态：
// 之后的目标轮次是从普通的会话历史里读到这些图的。
//
// 别的子命令带图一律判错。图留在编辑器里，比替用户把它们默默扔掉强。
//
// # 这一层不做的事
//
// 不做重试，不做「你是不是想说」，也不把 CAS 修订号露给人看。一次因为状态不对
// 而被目标服务拒掉的调用，回的是一句「这条命令在当前状态下不成立，敲 /goal 看看
// 现在能干什么」——修订号是这一层和那台服务之间的事，跟人无关。
