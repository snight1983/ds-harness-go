// Package timecontext 是时间这一层：每一步开始之前，往对话里落一条说得出
// 「现在几点、按哪个时区读、离上一次过了多久」的读数，并且守住一条不变量——
// 落库的读数必须是**当时真的**在那个位置采的。
//
// 源: packages/context/time-context/src/index.ts
//
// # 这一层管什么
//
// 一件事，分三步：
//
//  1. **该不该注入。**[ShouldInject] 按配置的间隔做节流，
//     [PreviousBaseline] 挑出这一步该用的基线时刻。
//  2. **写成什么。**[RenderText] 排出面向模型的那三行，[ReadingSource] 造出
//     这条消息该带的来源。两者的产物是**同一段字节**，这一条被不变量钉死。
//  3. **认不认得回来。**[ValidateSession] 把日志里每一条本包署名的读数
//     重排一遍再逐字比对，对不上就是伪造的。
//
// [Install] 把这三步接到 agent 的步骤准入瀑布上（DSH 的 `agent/pre-step` 钩子）：
// 每一步开始之前，在里层已经拟好的那批消息末尾补一条读数。真正把它写进日志的是
// agent 循环——它把准入决定里那些消息挨个追加在 `step/start` 之后、请求头之前，
// 而那正是 [PreparationPosition] 认的那个位置。
//
// 不管的：这条读数落盘之后谁来验。[ValidateSession] 写好了，把它接进
// [github.com/snight1983/ds-harness-go/invariants] 是装配方的事。
//
// # 为什么要有这一层
//
// 模型不知道今天几号。不给它，它会把训练数据截止那天当成现在，于是「上周」
// 「明天」这类相对日期一律算错，而且错得很自信。给了之后还有第二个问题：
// 一段长对话里，模型分不清「上一条消息是三秒前还是三天前」——那两种情况下
// 「继续刚才那件事」的含义完全不同。所以读数里除了时刻，还有一段耗时。
//
// # 时区从哪来
//
// docs/DESIGN.md 第三节定的：**由消费方传**，也就是 [Config.TimeZone]。
//
// DSH 那边取的是浏览器时区，逐条用户消息由 Host 带上来，还要处理同一回合里
// 几条消息报了不同时区、以及一条都没报这两种情况。服务端没有「当前用户的
// 浏览器」，而那个字段的产出方（host/apiproxy、client/runtime）整个不在移植
// 范围里，所以 `request-zone.ts` 那三个导出在这里没有对应物，mixed 和 missing
// 两条分支连同它们那两句「去问用户」一起消失。
//
// 读数正文的第二行保留下来，因为它承担的**模型行为**没有变：不说清楚的日期
// 时间该按哪个时区理解，得有人告诉模型。只是那一行现在只有一种写法。
//
// # 这里和 DSH 不一样的地方
//
//  1. **没有 cordis，也没有 schemastery。**[Config] 是普通结构体，
//     默认值补在 [Config.Resolve] 里。DSH 的 `refreshIntervalMs` 是一个毫秒数
//     配一整套 `Number.isSafeInteger` 校验；这里是 [time.Duration]，整数性和
//     量纲由类型系统承担，运行期只剩「不许是负数」一条。
//  2. **缺省时区是 UTC，不是宿主机时区。**DSH 用
//     `Intl.DateTimeFormat().resolvedOptions().timeZone` 兜底。Go 里没有这个
//     东西：[time.Local] 的 `String()` 是字面量 "Local"，不是一个 IANA 名字，
//     而这个名字要**原样进提示词**、还要被不变量重新解析。所以缺省是
//     [DefaultTimeZone]，而且 [Config.Resolve] 显式拒掉 "Local" 这个写法。
//  3. **本包不 import time/tzdata。**往每个依赖方的二进制里塞进四百多 KB
//     时区数据不是一个库该替人做的决定。缺省的 UTC 那条路压根不碰文件系统，
//     所以零配置永远能跑；配了别的名字而宿主机没有 zoneinfo 时，
//     [Config.Resolve] 报出来的那句话里写着两种修法。
//  4. **时间戳排法只有一个时区参数。**DSH 的 `formatTimestamp` 收一个
//     formatter 再收一个时区名，因为它兜底那个 formatter 是拿 `undefined`
//     造的、自己不知道落到了哪个时区。[FormatTimestamp] 收一个
//     [time.Location] 就够，方括号里的名字取它自己的 `String()`——少一个参数
//     就少一处「偏移量按 A 算、括号里却写着 B」的机会。
//  5. **偏移量排成 `+00:00` 而不是 `Z`。**Go 更常见的 `Z07:00` 在 UTC 上排出
//     单个字母，而 DSH 那边 `GMT` 被显式补成 `GMT+00:00`。一个字母的差别会让
//     同一时刻在两边渲染成不同的字节，而不变量正是靠重排再比对来认读数的。
//     [readingPattern] 因此也去掉了 `Z` 那条支路：一个本包排不出来的写法留在
//     正则里，等于给伪造留一个合法形状。
//  6. **`number | undefined` 换成一个值加一个布尔。**[Reading.HasPrevious]，
//     理由和会话引用那处逐字相同：Unix 纪元零点是一个合法时刻，
//     拿零值当「没有」会撞车。
//  7. **渲染的输入聚成了一个值。**DSH 的 `renderText` 收七个位置参数。
//     [Reading] 把「这次观察到了什么」聚起来，好处是不变量复核时可以拼出
//     **同一个**值再重排一遍，而七个散参数很容易在复核那一侧漏传一个。
//  8. **不变量比 DSH 的强一格。**DSH 只在浏览器时区恰好唯一时才重排时间戳去
//     比对，因为它兜底用的是宿主机进程时区、而不变量那一侧拿不到同一个进程。
//     这里时区由装配方给、注册这条检查时一起交进来，所以**每一条**读数都要
//     重排一遍逐字比对。换来的是 DSH 那条「按本回合用户消息重推浏览器时区」
//     的检查整个消失——它没有对应物，也不需要。
//  9. **来源形状少查一条。**DSH 还要查 `Object.keys(source).length !== 4`，
//     防的是有人往来源对象上多挂字段夹带进提示词。[llm.PluginSource] 是个
//     封闭结构体，多挂不进去。
//  10. **注入失败是降级，不是故障。**DSH 的 `apply` 里那两处读日志的调用直接抛，
//     于是一条读不回来的历史事件会把整个步骤准入带崩。[Install] 装上的那条规则
//     改成记一行警告然后原样放行：这一层是给模型补上下文的，让 agent 因为算不出
//     「离上次过了多久」而停摆，代价和收益完全不成比例。它也**不会**退而求其次
//     去注一条基线可疑的读数——那句 "Elapsed since…" 会被模型当成事实，而一个错
//     的基线正是本包自己那条不变量要拦的东西。
//  11. **不变量那一侧的接线不在本包。**`invariant.ts` 里的 `apply` 只是往注册表上
//     挂一个安装器，核心的 [ValidateSession] 在这里写完了；把它接进
//     [github.com/snight1983/ds-harness-go/invariants] 要装配方在写路径上把待写的事件接在末尾一起交进来，
//     成例是 core/session 的 `session.Trace`。
//
// # 覆盖率为什么到不了 99%
//
// docs/DESIGN.md 第九节给纯逻辑包定的线是 99%，低于这个数要在源码里写明为什么。
// 本包的用例覆盖到 98.7%，没覆盖到的**只有三条**语句，而且是同一种：
// [decodeTurnStart]、[decodeStepStart]、[decodeUserMessage] 里那句
// 「负载解出来不是这个类型」。[session.DecodeData] 按事件类型分发，
// 一条 turn/start 只会得到 [session.TurnStartData]，所以这一支构造不出来。
//
// 留着它们而不是断言掉，是因为一次分发错位的后果在本包特别贵：看漏一个回合
// 边界会让 [PrecedingStepContextTime] 跨过回合去取基线，而那是一段**静默**
// 错掉的耗时——模型会读到一个看起来很正常、实际上把用户离开的几个小时算进去的
// 数字，没有任何地方会报错。
