// Package searchstore 是会话全文检索的落地实现：把已落地的会话折成文档存进一份
// 介质，查询时和此刻活着的那些会话并起来排，交出带游标的一页。
//
// 源: packages/session-query/session-query-sqlite
//
// 它实现 [github.com/snight1983/ds-harness-go/feature/sessionquery.Searcher]，
// 挂进 `sessionquery.Options.Searcher` 就生效；不挂的话那两个检索方法照旧报
// `SESSION_QUERY_SEARCH_DISABLED`，别的读法一概不受影响。
//
// # 一次检索走过的四步
//
//	┌──────────────┐        ┌──────────────┐
//	│ 已落地的会话 │        │ 活着的会话   │
//	└──────┬───────┘        └──────┬───────┘
//	       │ ① 对账                │ ② 就地折
//	       ▼                       ▼
//	┌──────────────┐        ┌──────────────┐
//	│ 介质里的文档 │        │ 内存里的文档 │
//	└──────┬───────┘        └──────┬───────┘
//	       │ ③ 在库里找、在库里排   │ ③ 在进程里找、在进程里排
//	       └───────────┬───────────┘
//	                   ▼ ④ 并起来、再排一次、切出这一页
//	            ┌─────────────┐
//	            │ 一页 + 游标 │
//	            └─────────────┘
//
// ① **对账**：每个已落地会话都带一个变更令牌（
// [github.com/snight1983/ds-harness-go/feature/persistence.Snapshot.Revision]）。
// 介质里每一组文档也盖着上次索引时的那个令牌。两个数对得上就跳过，对不上才重读、
// 重折、整组换掉；令牌还在、会话没了的，整组丢掉。
//
// ② **活的不进介质**。正被推进的会话每敲一个字都会变，把它写进一份多个副本共用的
// 介质，等于让每一次输入都变成一次跨机写。它们在本进程里当场折、当场算分。
//
// ③ **同一句话在两侧算出同一个分**。库里那一侧的比对和计分由
// [github.com/snight1983/ds-harness-go/adapter/datastore.DocUnit.Match] 做，
// 进程里这一侧用 [github.com/snight1983/ds-harness-go/adapter/datastore.Fold]
// 折出同一份文本再数同样的次数——两侧共用一个折法，才不会出现「库里命中、
// 内存里不命中」。
//
// ④ **活的盖住落地的**。同一个会话两边都有时，活的那份才是最新的，落地的那份在
// 查询里被整组排除掉。
//
// # 为什么不是全文索引
//
// DSH 那份实现用的是 SQLite 的 FTS5。本仓库不用它，也不用 Postgres 的
// tsvector + GIN，改成**逐字的子串扫描**（理由写在
// [github.com/snight1983/ds-harness-go/adapter/datastore.DocUnit] 上）：这两套
// 索引都要先把文本切成词，而它们的切词器都不切中文——一整句中文会变成一个词元，
// 于是「找一个词」永远不命中。那种失败是静默的：查询跑绿了，只是一条都没有。
// 子串扫描慢，但它答得对。
//
// 代价要说清楚：一次查找是在整个语料上扫一遍，代价随语料大小线性增长。要真正的
// 倒排索引，是换一种介质（把这个包换掉），不是在这里加一层分词器。
//
// # 游标和世代
//
// 一页结果配一个游标，游标里记着三样：这次请求的**指纹**、这份语料的**世代**、
// 翻到第几条。指纹对不上说明续的不是同一次查询，报 `SESSION_QUERY_INVALID_CURSOR`；
// 世代对不上说明语料在两页之间变过了，报 `SESSION_QUERY_STALE_CURSOR`，让调用方
// 从第一页重来——继续翻会漏掉或者重复，而那两样都不会有人发现。
//
// 新增: DSH 那边的世代是**一个进程内的自增计数器加一个进程标识**。本仓库的会话
// 检索要在多个副本上同时跑，那种世代在别的副本上算出来必然不同，同一份没变过的
// 语料会被判成过期。这里的世代改成一份**内容指纹**：所有已落地会话的令牌，加上
// 所有活会话的文档指纹，一起哈希。任何副本、任何时刻，只要语料没变，算出来就是
// 同一个数。
//
// # 不做什么
//
//   - **不自己写 SQL。**每一句都由
//     [github.com/snight1983/ds-harness-go/adapter/datastore] 那边的文档集发出去，
//     理由见那个包的包文档。
//   - **不索引活会话。**它们只在本进程内存里折，不落介质，见上面第 ②
//     步。
//   - **不做倒排索引、不分词、不做词干和同义词。**查询是逐字的子串比对，只有
//     大小写和连续空白不算数。
//   - **不定义会话头、事件、表面这些形状。**它们归
//     [github.com/snight1983/ds-harness-go/sessionlog] 和
//     [github.com/snight1983/ds-harness-go/feature/sessionquery]；本包只把它们
//     折成文档再折回来。
//   - **不管介质的生命周期之外的事。**建库、备份、迁移、保留期限都不在这里。
//   - **不落本机文件。**除了 SQLite 那一支由装配方在 DSN 上指定的库文件，
//     本包不碰宿主机的任何路径。
package searchstore
