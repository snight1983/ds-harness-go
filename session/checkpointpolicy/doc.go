// Package checkpointpolicy 在三处语义边界上立起耐久检查点。
//
// 源: packages/session/session-checkpoint-policy/src/index.ts:1-5
//
// 它自己一行状态都不存，装上去之后只做一件事：在「这一步的后果将要跑到会话日志
// 管不着的地方去」之前，先把日志已经记下的那一段刷到耐久为止。
//
// # 三处边界，以及为什么是这三处
//
// 一是**模型请求派发前**。请求本身（system、消息、工具表）在派发前就已经落进日志
// 了，可它还只在内存里。适配器一旦把它发出去，钱就开始花，模型也开始产出——此后
// 进程挂掉，恢复出来的会话会缺掉这次请求，而它的回答已经在世界上存在过了。
//
// 二是**顶层工具调用派发前**。工具体是这套东西里唯一能改到会话之外的世界的地方：
// 写文件、发请求、跑命令。那条「我要调这个工具」的记录必须先耐久，否则一次崩溃
// 之后会留下一个谁都不知道发生过的副作用。
//
// 三是**每个步骤开始前**。这一下刷的是**上一步**提交的那一批（上次的回答、上次
// 那些工具结果）。放在下一步开头而不是上一步结尾，是因为一个步骤结尾未必有下文，
// 而下一次请求一定有——把它挂在必然会发生的那件事上，就不必再给「跑完了」单独找
// 一个收尾的钩子。第一个步骤上这一下没有前一批可刷，是有意的空转。
//
// # 失败一律关门
//
// 模型那道和工具那道都是**关门**的：检查点没过，下游的适配器和工具体一次都不起步。
// 这是这一层唯一有意义的失败姿势——刷不下去说明日志已经不可信了，此时再让副作用
// 跑出去，等于亲手制造一段没人记得的历史。
//
// # 嵌套派发不重复刷
//
// 一次工具调用在自己体内再派发工具（[core/tools.ExecutionInput.Parent] 有值）时不
// 再刷：外层那次进来时已经刷过，那条记录早就耐久了，里面再刷一遍是拿一次 fsync
// 换零信息。
//
// # 和 DSH 不一样的地方
//
// 新增: DSH 从 exec.agent 上直接拿到 Agent 对象再取它的会话。Go 的
// [core/tools.ExecutionInput.Agent] 是一把 [core/scope.Key]（只够走可见性和守卫那条
// 作用域链），发起者本身是挂在 context 上的，所以这里改用
// [core/agent.CurrentInitiator]。这不是绕路：agent 循环填那把 key 时填的正是
// initiator.Scope().Key()，两者由构造保证是同一个 agent，而循环自己找会话走的也是
// 这一条（core/agentloop/toolcalls.go:109）。
//
// 新增: DSH 那道模型检查点是一个 async generator，刷盘要等到消费方来拉第一块时才
// 真的发生——那是「在同步的钩子里没法 await」逼出来的写法，不是它想要的语义。Go 的
// [llm.StreamRule] 就是个能阻塞的普通函数，所以这里刷完再调 next，失败在
// [llm.Runtime.Stream] 返回时就报出来，而不是等到第一次迭代。要保的那条
// （耐久之前不许派发）两种写法都保得住，早报的那种少一层间接。
//
// 新增: DSH 那份 invariant.ts 装的是个空函数体，它自陈没有运行期不变量可守——次序
// 由被拦的那几条瀑布和持久化那一层自己保证，这个无状态策略不拥有任何独立的可变关系。
// Go 这边同理，本包不往不变量注册表上登记任何东西。
