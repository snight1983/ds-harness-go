// Package datastore 是本仓库**唯一**操作数据库的地方。
//
// 新增: 上游没有对应物。它是本仓库的一条结构约束，不是一个被移植过来的包，
// 理由见下面「为什么只能有一个」。
//
// # 为什么只能有一个
//
// 在这个包之前，仓库里有两处各自开连接池、各自建表、各自写 SQL 的代码：会话日志
// 一处，键值中枢一处。两处的形状是抄来抄去的——限定到 schema 不靠 search_path、
// 建表包在一次咨询锁里、盖号放在最后一步、值列用 TEXT 不用 jsonb、标识符长度要查——
// 连注释里都写着「理由同另一个包里那个同名函数」。再添一种数据库就是四处。
//
// 抄出来的东西会分叉。两处对同一件事的处置一旦差一点（一个查了标识符长度、
// 一个没查；一个在可重复读里读、一个在缺省隔离级别里读），差出来的那一点不会在
// 任何一处的测试里露头，它只在换后端、换数据库、换部署的时候露头，而那时候
// 没有人记得为什么两边不一样。
//
// 更要紧的是**调用方**。两处意味着一个要存数据的模块得先知道自己该去敲哪一扇门，
// 还得学会两套词汇。它凭什么知道？后面挂的是 Postgres 还是 SQLite、是不是哪天
// 换成别的，和它没有关系。
//
// 所以：**只有本包碰 database/sql，只有本包写 SQL。** 这条由
// tools/dbcheck 那道门禁压着，不是靠自觉。
//
// # 别的模块怎么用
//
// 不用。它们只声明自己的业务接口，由适配层去实现：
//
//	session/persistence.Backend   ← datastore/sessionstore
//	storage.KVProvider            ← datastore/kvstore
//
// [github.com/snight1983/ds-harness-go/session] 和
// [github.com/snight1983/ds-harness-go/storage] 这两棵树里没有、也不许有任何一处
// 提到数据库。依赖的方向是反过来的：适配层认识业务接口，业务接口不认识适配层。
//
// 一种根本不同的介质（对象存储、远端 API）不进本包，它自己去实现同一道业务接口。
// 本包是「关系库这一种介质」的实现，不是所有持久化的总入口。
//
// # 对外只有两种形态
//
// 本包不提供「随便写一句 SQL」。它只认两种通用形状，都不带任何领域含义：
//
//	记录集 [RecordUnit]   若干张 (键 → 一段不透明 JSON) 的表，外加一个可选的单例槽。
//	日志集 [LogUnit]      若干条流，每条流是一份头加一串按 seq 升序、可以从头弹出的条目。
//
// 键值中枢落在记录集上；会话日志落在日志集上。两者都不曾要求本包认识
// 「会话」「单元」这些词。
//
// 一种新的业务需求如果这两种形状都装不下，那是往本包**加一种形状**，而不是在
// 使用方那边写一句 SQL——加形状要过一次设计，写一句 SQL 不用，这正是分岔的起点。
//
// # 介质、命名空间、实例标识
//
// 一个 [Medium] 是一份介质：一个连接池，加一个命名空间。命名空间在 Postgres 上
// 是一个 schema，在 SQLite 上是表名的一段（那里没有 schema 这个东西，理由见
// [sqliteDialect.Qualify]）。两种落法之下，同一个库里的两个命名空间都是两份
// 互不相干的介质。
//
// 每份介质在第一次打开时盖上一个实例标识，此后不变。它拌进 [Revision] 里，
// 让两个各自独立的介质发出的令牌不会比出相等——各自从 0 数起的计数器不拌来源
// 就一定会撞。
//
// # 方言
//
// 语句里数据库之间会分歧的那几处（占位符、限定标识符、咨询锁、只读事务的隔离级别、
// 取大的那个函数）收在 [Dialect] 后面。加一种数据库是加一个 [Dialect]，不是加一个包。
//
// 随包发出的有两个：[Postgres] 和 [SQLite]。前者是服务化部署那一种，后者是单机
// 落一个库文件那一种。两个都进本包自己的测试，因为一种方言自己跟自己是没有分歧的。
//
// SQLite 那一支有两件事本包**管不了**，得由装配方在 DSN 上设：`busy_timeout`
// （否则两条写事务撞上时后到的那条当场失败而不是等一等）和 `foreign_keys`
// （否则条目表那道外键不生效，Postgres 那一轮拦得住的东西这一轮拦不住）。
// 两件事都是连接上的状态而不是语句里的东西，所以它们进不了 [Dialect]——细节
// 见 [SQLite]。
//
// # 不在本包里的失败
//
// 连不上库、事务被中止、死锁重试——这些没有对应的分类码，原样往上冒，只裹一层
// 说明是哪一步。本包自己认得出来的那几种（流不在、版本不符、名字不合法、
// 介质里的值坏了、已经关掉了）见 error.go。
