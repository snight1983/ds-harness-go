// Command portcheck 管住这次移植的两件事：**有没有漏看**，以及**填进去的那一格对不对**。
//
// 新增: DSH 没有对应物——它不是被移植过来的，是这次移植自己需要的账本工具。
//
// 两件事分成两个模式，因为它们的性质不一样：
//
//	-mode sync    把 dsh-exports.tsv 同步进裁决表，新符号一律以 PENDING 落进去。
//	-mode check   门禁。默认答案是「不通过」，任何一条不满足就退出码非零。
//	-mode audit   审查报告。**不阻断**，输出是一份给人排队用的工作队列。
//
// 门禁（check）和审查（audit）的分工是这个工具的全部设计：
//
//   - 门禁问的是「这一格填了吗、填的名字存不存在吗」。它是机械的，所以可以阻断——
//     一条不满足就是确凿的错，没有解释的余地。
//   - 审查问的是「填进去的那一格对不对」。它是启发式的，报出来的行**可能完全正当**，
//     所以它绝不阻断：把正当的东西判红会训练人去忽略红色，那比没有报告更糟。
//
// 具体每一条检查在做什么，写在 main.go（门禁）和 audit.go（审查）各自的文件说明里。
