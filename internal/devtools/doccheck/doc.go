// Command doccheck 是文档那一侧的门禁：它管住「代码和文档没有各走各的」。
//
// 新增: DSH 没有对应物——它不是被移植过来的，是本仓库自己需要的工具。
//
// 它是**阻断式**的：任何一条不满足就退出码非零。这一点和 portcheck 的 audit 模式
// 相反，理由也相反——这里每一条都是机械可判的事实（文件在不在、链接指不指得到、
// 章节有没有），没有「可能完全正当」的余地，所以判红就是真的错。
//
// # 查什么
//
//  1. **包和文档双向对齐。**docs/packages.md 里每个 Go 包恰好一行映射：
//     包表来自 `go list ./...`，多一行（映射了已经不存在的包）、少一行（包没写进映射）、
//     重复一行，三种都报。
//  2. **映射指向的文档真的存在**，而且**进了侧栏**（docs/_sidebar.md）——
//     写了一篇没人能点到的文档，和没写差不多。
//  3. **模块文档的骨架齐全。**docs/modules 下的每一篇，必须有一级标题以及定位、
//     架构、生命周期与并发、失败语义、能力边界、对应的 DSH 能力、相关源码这几个章节。
//     查的是章节在不在，不是内容对不对——后者机器判不了。
//     按目录取而不是按侧栏「详细模块」那一节取：侧栏分组是给人读的编排，
//     把一篇文档挪个分组不该让它脱离检查。
//  4. **所有本地链接指得到东西。**README.md 加 docs 下每一篇 Markdown，
//     逐个链接解析：越出仓库的报，指向不存在文件的报。外部 URL 和纯锚点跳过。
//  5. **每个包都写了自己的禁区。**包注释末尾要有一节标题为「# 不做什么」的小节，
//     列出这个包**不**负责的事以及各归谁。跟第 3 条一样，查的是这一节在不在。
//     写死成一个固定标题、而不是让各包自选措辞，是因为措辞一散，判据就没了。
//     取包注释走 go/parser：哪一段算包注释（紧挨 package 子句、中间不许隔空行）
//     是编译器定义的规则，自己扫一遍注释行迟早会和它分叉。测试文件里的不算。
//
// # 两处刻意的例外
//
//   - **docs/portmap 整个目录跳过。**那几份是上游移植清单，里面的路径按**上游仓库**
//     解释（packages/xxx/src/yyy.ts），本仓库里当然找不到——拿本地链接的规矩去查它，
//     报出来的全是噪音。
//   - **被 Git 忽略的目录里的包跳过。**`go list ./...` 会把临时试验目录里的包也列出来，
//     那些包不进版本库，也就不该要求有文档。判据是 `git check-ignore`，
//     不是路径名约定。
//
// # 不做什么
//
//   - **不评价文字质量。**包注释在不在、章节在不在、链接指不指得到，这些机器判得了；
//     一篇文档写得好不好判不了，也不该由退出码来判。
//   - **不查外部 URL 和纯锚点。**前者要联网，后者要解析标题，两样都会把网络抖动和
//     渲染细节算进门禁里。
//   - **不查 docs/portmap 里的路径。**那几份账本的路径按 DSH 快照解释，
//     由 internal/devtools/portcheck 验真。
//   - **不查被 Git 忽略的目录里的包。**它们不进版本库，也就不该要求有文档。
//   - **不管包之间的 import 方向，也不管数据库和磁盘那两条界线。**分别归
//     internal/devtools/layercheck、internal/devtools/dbcheck、internal/devtools/oscheck。
