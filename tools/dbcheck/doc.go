// Command dbcheck 是数据库那一侧的门禁：它管住「除了 datastore，谁都不知道下面
// 是个数据库」。
//
// 新增: DSH 没有对应物——它不是被移植过来的，是本仓库自己需要的工具。
//
// 它是**阻断式**的：任何一条不满足就退出码非零。这里每一条都是机械可判的事实
// （某个 import 在不在、某段字符串是不是一句 SQL），没有「可能完全正当」的余地。
//
// # 为什么要有这道门禁
//
// 在它之前，会话持久化和键值中枢各自开自己的连接池、各自建自己的表、各自拼自己
// 的 SQL。两份几乎一样的 qualify、两份 63 字节的标识符上限、两套建表语句。后果
// 不是「重复」这么轻——它意味着换一种介质要改两处，而且业务层的类型签名里就写着
// `*sql.DB`，于是「后面用的是什么数据库」变成了业务代码的事。
//
// 现在数据库整个收在 datastore 底下：业务包只声明它要的那道业务接口，
// datastore 去实现。这件事光靠约定守不住——只要有一个人在 session 里 import 了
// database/sql，那道墙就没了，而且是悄悄没的。所以它得是一道跑得起来的检查。
//
// # 查什么
//
//  1. **SQL 语句文本只准出现在 datastore/ 底下。**判据是字符串字面量里有没有
//     SELECT…FROM、INSERT INTO、UPDATE…SET、DELETE FROM、CREATE/DROP/ALTER TABLE
//     之类的语句骨架。注释不算——注释里说得清「这里为什么要一句 upsert」是好事。
//  2. **database/sql 和各家驱动只准出现在 datastore/ 和 cmd/ 底下。**
//     cmd/ 是装配点：谁来部署、连哪个库、池子开多大，那是它的事，不是业务包的事。
//     除了写死的那份驱动名单，还有一条按路径命名的兜底规则，免得换一个驱动就
//     从门禁底下溜过去。
//  3. **datastore 这个包只准被 datastore/、cmd/、tools/ 引用。**业务包引的必须是
//     业务接口（session/persistence 的 Backend、storage 的 Backend），不是某个
//     具体实现。引了具体实现，「换一份介质」就又变成了一次跨包改动。
//
// # 一处刻意的例外
//
// **tools/dbcheck 自己整个跳过。**这个工具的源码里必然有 "database/sql" 这个串、
// 也必然有一条认得出 SQL 的正则，而那条正则认得出它自己。不跳过的话它每次都
// 判自己红。
