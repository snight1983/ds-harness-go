// Command oscheck 是文件系统那一侧的门禁：它管住「业务代码不碰跑着这个进程的
// 那台机器的磁盘」。
//
// 新增: DSH 没有对应物——它不是被移植过来的，是本仓库自己需要的工具。
// 它和 tools/dbcheck 是同一件事的两半：那一半管数据库，这一半管内容存储。
//
// 它是**阻断式**的：任何一条不满足就退出码非零。这里每一条都是机械可判的事实
// （某个 import 在不在、某个 os 函数被不被调），没有「可能完全正当」的余地。
//
// # 为什么要有这道门禁
//
// 这个服务跑的地方**没有可用硬盘**。存储全部落在数据库（datastore）和对象存储
// （fs/objectstore）上，为的是它能分布式部署。一旦某处代码隐含「有那么一台机器、
// 有那么一个文件系统命名空间」，这个服务就被绑死成单点：每个副本都得先有那些
// 目录，扩一个实例要先同步一遍磁盘，而那份内容和某台机器本来没有任何关系。
//
// 在它之前，preset/agentpresets 那一支散着二十处 os.* 调用，把「一份预设」钉死在
// 本地磁盘上；session.SessionHeader 上还挂着一条宿主机路径，被喂给一个对象键空间
// 的后端，于是那条挂载判定在生产里一次都没成功过。两件事都是同一个病。
//
// 现在内容读写整个收在 [github.com/snight1983/ds-harness-go/fs.FileSystem] 一条缝
// 上：业务包只声明它要读出什么、写进什么，挂对象存储还是挂外接硬盘是装配时的配置。
// 这件事光靠约定守不住——只要有一个人写下一行 os.ReadFile，那道墙就没了，
// 而且是悄悄没的。所以它得是一道跑得起来的检查。
//
// # 查什么
//
// 只查**非** _test.go 的文件。测试要造夹具、要临时目录，那是测试进程自己的事，
// 和这个服务部署成什么样无关。
//
//  1. **禁止调用 os 包里那些碰文件系统的函数**（打开、读写、建删、改名、
//     取工作目录……完整名单见 check.go 里的 bannedOSFuncs）。os 的其余部分不管：
//     os.Getenv、os.Exit、os.Stdout 和磁盘没关系。
//  2. **禁止 import path/filepath 和 io/ioutil。**前者是宿主机路径的语法
//     （盘符、反斜杠、符号链接），本仓库的路径一律斜杠分隔、由后端解释；
//     后者整个是文件 I/O。要拼路径用 path。
//
// # 分区
//
//   - **业务包**——两条规则全都管得到。
//   - **tools/ 和 cmd/**——放行。它们跑在**本机**上，是门禁工具和装配点，
//     不是这个服务的业务代码；一个装配点从磁盘上读一份配置文件正是它的活儿。
//   - **豁免名单**——只有两项，见下。
//
// # 豁免名单只有两项，不许再加
//
//   - **datastore/dbtest/**——数据库测试夹具，起一个临时 SQLite 文件再删掉。
//     它必须供别的包的测试 import，所以不能写成 _test.go，于是躲不进上面那条
//     「测试不查」。
//   - **llm/replay/**——快照测试用的假模型，从磁盘读回放脚本。它自陈见
//     llm/replay/doc.go：那些脚本是仓库里的测试数据，不是这个服务的运行时状态。
//
// 将来真写一个本地磁盘后端（fs/localdisk）时再往里加一条，那时它是**唯一一个**
// 被允许碰宿主机磁盘的业务包，而这件事正好是它存在的全部理由。
