// Package snapshot 把一份录下来的会话日志压成一份**可以提交进仓库、逐字节比对**
// 的快照。
//
// 源: packages/test-support/session-snapshot/src/index.ts:1-18
//
// 一份刚落盘的日志每跑一次都长得不一样：时钟在走，标识是随机铸的，一次落盘的
// 批次边界还会把同一串分块打包成不同的行。这三样都和「这一轮到底发生了什么」
// 没有关系，可是它们让 diff 全红。本包把这三样各按各的办法压平，压完两次跑
// 出来的同一个场景应当是同一段字节。
//
//	录下来的日志          ──▶  归零墙上时钟   ──▶  按类型编号的标识
//	  （每跑一次都不同）           createdAt/time        {{session:1}} {{message:2}}
//	                                                      │
//	                                                      ▼
//	          可提交的快照   ◀──  重打包分块   ◀──  请求头膨胀换记号
//	          （两次一模一样）      不看落盘边界       {{system}} {{tools}}
//
// # 和 feature/replay 是一对
//
// 本包**写**那份 `session.jsonl` 夹具，
// [github.com/snight1983/ds-harness-go/feature/replay] **读**它——两边说的是同一种
// 文本：第 0 行是会话头，此后一行一条事件或者一行打包过的分块。本包交出来的正文
// 把事件信封（seq/time/seq0/time0）整个省掉，而那正是 replay 那边
// `fillEnvelope` 要补回来的东西。
//
// # 标识为什么不是一律换成同一个记号
//
// 因为一份快照要验的东西里有一大半是**相等关系**：模型回填的那个 goal id 是不是
// 它收到的那个，子会话的父指针指不指得回父会话，一次审批的答复认不认得它那条
// 提问。全换成 `{{id}}` 之后这些关系全没了，日志变成一堆互相看不出联系的记录。
//
// 所以换的是**按类型、按第一次出现的顺序编号**的记号：同一个原值在父会话和它
// 那些孩子里换出来的是同一个记号，不同的原值换出来的一定不同。这也是
// [Normalize] 一次收一整个场景的全部日志、而不是一份一份收的原因——一份一份
// 压，父子之间那条线当场就断了。
//
// # 不做什么
//
//   - **不读也不写文件。**交进来的是正文，交出去的也是正文；夹具住在哪个目录、
//     叫什么名字，是调用方的事。
//   - **不比对，也不判断对错。**它只负责把两次跑的差异抹平，「抹平之后还不一样」
//     该怎么办是测试自己的事。
//   - **不管工作区文件快照。**DSH 那边还录二进制文件、符号链接和空目录，那件事
//     的前提是本机文件系统，本仓库没有（见 internal/devtools/oscheck）。
//   - **不起进程，也不驱动 agent。**录一份日志出来是
//     [github.com/snight1983/ds-harness-go/harness/smoketest] 那一侧的事。
//   - **不管协议转写稿。**DSH 那边还归一化 ACP 子进程的 stdout（JSON-RPC 帧、
//     rpcId 重编号），那一半跟着子进程一起没有移。
