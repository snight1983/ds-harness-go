// Package replay 是一台不要 API key 的模型：它把一段录好的会话日志倒回去，
// 让快照测试对着一份固定的模型转写稿把真的 agent 跑起来。
//
// 源: packages/test-support/llm-replay/src/index.ts:1-8
//
// 它存在的理由和 [github.com/snight1983/ds-harness-go/llm/mockserver] 是一对：mockserver 演的是**线路
// 怎么坏**（掉线、限流、SSE 从中间截断），本包演的是**模型说了什么**。崩溃恢复
// 那几条路要在精确的位置断开——第 7 轮的第 3 个分块之后进程死掉——真模型给不了
// 这个精确度，而一份录好的 JSONL 给得了。
//
// # 剧本从哪里来
//
// 素材就是一份落过盘的会话日志（`session.jsonl`）。本包**不录**：录就是「把真的
// agent 跑一遍、把 .jsonl 收走」，那是快照夹具那一侧的事。
//
// 推导只读两种事件。一是 assistant/chunk：按 (turn, step) 分组，每组就是一次
// stream() 调用吐出来的那串分块，每遇到一个 finish 就收一条。二是
// compaction/summary：它标了 [github.com/snight1983/ds-harness-go/compaction.SummaryData.LLMStreamCall]
// 时表示那次总结**恰好**是一次走本上下文 LLM 接缝的调用，于是拿它那份完整的
// RawOutput 在日志里的那个位置重造一次规范的成功流（每块一对 block-start /
// block-end，有用量就带上，最后一个 stop）。没标记的 rawOutput 不算——模板总结器
// 和远端总结器都可能留下完整输出而根本没碰这个上下文的适配器。
//
// 一组没有以 finish 收尾的分块是**一次抛出来的 stream()** 的指纹，推导当场拒绝：
// 那种情形从 assistant/chunk 里恢复不出来，得由旁挂文件明说。
//
// # 两种恢复不出来的形状
//
// 一是**一块都没吐就抛**（比如 HTTP 401，日志里只有一条带 error 的 turn/end），
// 二是**挂住等取消**（那是时序，不是分块内容）。要这两样的场景交一份旁挂文件
// （`replay.override.json`）：整份 [Entry] 数组是**替换**，`{"patches": [...]}`
// 是**增补**——留下每一条从 JSONL 推出来的调用，只把点名的那几个 0 基下标换掉，
// at 等于推导长度时追加（比如一次注入的瞬时故障之后那次重试）。补丁下标不许重复。
// 整份文档、每一条补丁和条目、每一个分块判别标签，都在读文件时验。
//
// # {{fromRequest:<正则>}}
//
// 剧本里的字符串可以埋这个占位符，用来填一个静态文件不可能知道的值——比如一个
// 随机铸出来的 goal id，模型必须把它原样回填进 update_goal。派流的时候拿**活的
// 请求**解算：语料是请求消息里每一个字符串叶子拿换行接起来，模式的**最后**一次
// 匹配赢，它的第一个捕获组（没有捕获组就是整段匹配）替回原处。匹配不上、模式
// 编译不了、占位符没闭合，三件事全都当场失败。一串连续 `}` 的最后两个才是结束符，
// 所以模式可以用 `[0-9a-f]{4}` 这样的花括号量词收尾，但不能在 `}}` 之后还有内容。
//
// 新增: Go 的 [regexp] 是 RE2，不认 JS RegExp 的反向引用和前后瞻。夹具里的模式
// 一律是普通的字符类和量词，用得上的都在 RE2 的范围里；真写了 RE2 不认的东西，
// 它会在编译那一步当场失败，而不是悄悄换一种匹配语义——这正是这条差异可以被接受
// 的原因。
//
// # 嵌套 agent：一个会话一份剧本
//
// 一个父 agent 派给进程内子 agent 的场景会录下不止一份日志：父（session.jsonl）
// 加每个孩子一份（session.1.jsonl、…）。每个 agent 是同一个上下文上自己那个会话，
// 所以本包按调用方那个会话 id（[github.com/snight1983/ds-harness-go/llm.GenerateOptions.SessionID]）
// 分开各自的游标。
//
// 活会话的 id 每一跑都是新随机的，绝不等于录下来的那些，所以绑定靠**第一次调用的
// 次序**：剧本按头里的 createdAt 排（父在前——它必须先流出来才谈得上派活），
// 第一个发起调用的活会话认领第一份剧本，下一个新会话认领下一份，此后各自推进
// 自己的游标。一次不带会话 id 的调用是同一个匿名会话，绑主剧本。活会话比录下来的
// 剧本还多时大声失败。
//
// # 和 DSH 不一样的地方
//
// **新增: 派发不出去的那两种失败直接从第二个返回值交出去。** DSH 那边监听器必须
// 交回一个 AsyncIterable、不能抛，所以「来了一个没录过的会话」和「剧本用完了」
// 被推迟到生成器里才抛。Go 的 [github.com/snight1983/ds-harness-go/llm.Adapter.Stream] 本来就把「派发
// 不出去」和「流走到一半失败」分成两处（见那个接口的文档），这两件事都发生在
// 一个分块都还没吐之前，所以它们就是第二个返回值。这不是行为差异——运行时对两处
// 失败的归一是一样的——是把一个 TS 那边绕开语言限制的写法还原成它本来的形状。
//
// **新增: 取消走 ctx，不走 AbortSignal**，与本仓库每一处一致。挂住那一条等的是
// ctx.Done()，交出去的是 ctx.Err()；运行时看见 ctx 已经取消就把它归一成一个
// aborted 的终止分块（见 llm 那边的 adapterFailureChunk）。
//
// **新增: DSH 的插件 Config 和 ReplayConfig 在这里合成一个 [Config]。** 那边分成
// 两个，是因为 cordis 交进来的是一份 schemastery 验过的插件配置，`apply` 再把
// 环境变量的默认补进去变成解算好的那一份。Go 没有装载器，[ResolveFromEnv] 就是
// 那一步：收一份 Config、把没给的字段从 DSH_SNAPSHOT_* 补上、验模态、交回补好的
// 同一个类型。
//
// **新增: 头的解析直接落进 [github.com/snight1983/ds-harness-go/session.SessionHeader]。** DSH 手挑
// id / createdAt / seedLength 三个字段并逐个 typeof 判类型，是因为它那边没有一个
// 认得这份头的解码器；Go 这边有，读回来就是那个类型。
//
// # 不移的那一半
//
// **新增: 没有 cordis 插件那三样（name / inject / apply）。** 装配方直接调
// [Install]，它收的是运行时、持有作用域和一份配置，全是显式入参。
//
// # 覆盖率为什么停在 98.9%
//
// 本包读写文件、装运行时、落就绪标记，不是纯逻辑包，按 docs/DESIGN.md 那条规矩
// 得在这里写明差在哪。剩下没盖到的六处全是**走不到**的分支，不是没写用例：
//
//   - [ResolveScriptedEntry] 里排条目、排请求消息、以及在自己刚排出来的那份字节上
//     攒语料——这三处的入参都是本包刚生成的合法 JSON，排不出去或读不回来意味着
//     [github.com/snight1983/ds-harness-go/llm] 那边的编解码坏了，而那是那个包自己的用例该管的事。
//   - [ParseSessionLog] 把补好信封的字段表排回去：那张表是从一行合法 JSON 解出来的。
//   - [DeriveScript] 在收到 finish 分块时的那次收尾：收尾只在最后一块不是 finish
//     时失败，而这一处的最后一块正是那块 finish。
//   - 旁挂文件在确认整份文档是合法 JSON、且首字符是 `[` 之后再解成条目数组：
//     这一步不可能失败。
//
// 这六处留着而不是删掉，是因为它们各自守着一个「本包自己写错了」的口子；把它们
// 换成 panic 或者忽略错误，换来的是一份更难查的现场，不是更高的覆盖率。
