// Package mockserver 是一台按剧本演故障的 OpenAI 兼容聊天补全服务器。
//
// 源: packages/test-support/llm-mock-server/src/index.ts:1-7
//
// 它存在的理由只有一个：让「模型接口坏掉之后我们怎么办」这件事可以被测试。真的
// 供应商不会在你想要的时候掉线、限流、或者把 SSE 流从中间截断，而这三件事恰恰是
// 恢复策略里最要紧的分支。所以本包把这些故障做成可以点名的剧本条目，每接进来一个
// 聊天补全请求就消费一条。
//
// 它**不重试、不解释、也不替调用方做任何策略判断**。剧本说重置连接就重置连接，
// 说限流就发 429。判断「这时候该不该重试」是被测那一侧的事，混进来会让测试自己
// 变成一个需要被测试的东西。
//
// # 路由
//
// 只有 POST 到以 /chat/completions 结尾的路径才消费剧本。方法不对、路径不对、
// 令牌不对、请求体不是 JSON——这四种都按普通的 4xx 回掉，**不动剧本游标**。
// 这一条是有意的：测试里一次拼错的 URL 不该把后面所有用例的剧本错开一格。
//
// # 剧本用完了会大声失败
//
// 默认情况下剧本消费完之后再来的请求收到一个 500 和 MOCK_SCRIPT_EXHAUSTED。
// 想让最后一条无限重复，得显式打开 [Options.RepeatLast]。悄悄循环回第一条是
// 最糟的选择：一个多发了几次请求的测试会一直绿着，而它测的东西早就跑偏了。
//
// # 随机
//
// 剧本里写 random 的位置由带权重的伪随机挑一个具体行为。种子可以指定
// （[Options.RandomSeed] 配 [Options.HasRandomSeed]），不指定就生成一个并从
// [Server.RandomSeed] 交出来——**跑挂了的那一次必须能原样重放**，所以种子从来
// 不是内部细节。
//
// [DefaultRandomWeights] 那份权重是压力配方，不是对线上故障频率的估计。
//
// # 生命周期
//
// [Server.Close] 是幂等的，并且会强行掐断 stall 那种挂着不动的连接——否则一个
// 用了 stall 的测试跑完之后进程退不掉。
