// Package policy 决定一份工具结果多大算大，以及把它挪走之后拿什么替换给模型看。
//
// 对应 DSH 的 @deepseek-ai/dsh-spill-policy（packages/spill/spill-policy）。
//
// 源: packages/spill/spill-policy/src/index.ts:1-45
//
// # 它只决定「什么时候」，不拥有存储也不拥有预览
//
// 存全文是 [github.com/snight1983/ds-harness-go/spill.Store] 的事，切头尾是
// [github.com/snight1983/ds-harness-go/util/outputretention.TextRetainer] 的事。本包做的是三件：
// 判断这份结果超没超预算、把全文交给后端、把「预览 + 句柄 + 取回说明」拼成
// 一段替换内容。
//
// # 上限是**替换后**的上限
//
// 这是本包最容易写错、也最要紧的一条：预算不是分给预览的，是分给**整段替换文字**的。
// 一个天真的实现会拿满预算切预览、再把那句说明接在后面，于是替换出来的东西比上限大，
// 对一份刚刚超标的结果甚至比原文还大——那就成了「为了省上下文而多花上下文」。
//
// 所以这里先按**最坏情况**给那句说明留出位置：拿「全丢」这个计数去估它的长度。
// 真实的丢弃数一定不大于全文字节数，位数也就不会更多，于是留出来的位置一定够。
//
// 留完之后如果连那句说明本身都塞不下（上限给得极小，或者后端的句柄很长），
// 就**不换**：换了就破了上限这个承诺。已经写下去的那份产物是个无害的孤儿。
//
// # 尽力而为，绝不把一次成功的调用变成失败
//
// 没有会话归属、后端存不下、说明塞不进上限——这三件事的处置都一样：记一条日志，
// 原样把内联结果交出去。一次外置失败**永远**不许让一次成功的工具调用变成 IsError，
// 也不许把内容藏起来。
//
// # 和别的执行后规则相处
//
// 它先调 next 再动手：下游（比如一个钩子）先把结果定下来，本包约束的是它定下来的
// 那份。所以工具自己那份异步投影先跑，然后才轮到通用的封顶；一个换过内容的钩子，
// 换上去的那份同样会被封顶；换**值**的裁决和 block 裁决则原样穿过去——
// 换值要回注册表重新验一遍、重新渲染，这条呈现规则不能在同一次互斥的裁决里
// 又去换内容。
//
// # 和 DSH 不一样的三处
//
// 新增: DSH 的 Config.maxInlineBytes 可以省略，省略就一条监听器都不装。Go 这边
// 「不启用」由调用方**不叫 Install** 表达——0 在 DSH 那边是一个合法的上限
// （表示什么都外置），所以拿零值当「没给」会吃掉一个能表达的配置。
//
// 新增: DSH 靠结构类型 SpillPolicyExec 从 exec.agent.session.header.id 里读出会话。
// Go 这边 [github.com/snight1983/ds-harness-go/core/tools.Execution.Agent] 是一个不透明的作用域键，
// 从它到会话 id 的映射由调用方在 [Config.OwnerOf] 里给。
//
// 新增: DSH 还有第二条胳膊，给 Code Mode 的 tools/code-dispatch-log 瀑布封顶。
// 那条瀑布在本仓库不存在（Code Mode 整个不移植，见 docs/DESIGN.md），
// 所以本包只有面向模型的那一条。
//
// # 存这一次用的是背景 ctx
//
// [github.com/snight1983/ds-harness-go/core/tools.PostRule] 的签名里没有 ctx——执行后瀑布跑的时候
// 这次调用已经收敛了。DSH 那边这个监听器同样拿不到调用方的信号。所以存全文用的是
// 一个独立的背景 ctx：它不该被那次已经结束的调用连累，中途撤掉只会留下一个
// 存了一半的句柄。
