// Package domainjobs 是后台作业那条缝的**多副本实现**：账本落在一张域表上，
// 每个副本都读得到；执行资源留在起这件活儿的那个进程里，谁都拿不走。
//
// 新增: 整个包都是本仓库自有的，DSH 没有对应物。它那台注册表
// （packages/jobs/jobs-local）是一个进程里的一张 map——那是对的，DSH 是一个单进程
// 桌面工具。本仓库要多副本部署，一张进程内的 map 会让 A 副本起的作业在 B 副本上
// 根本不存在：`job_list` 少一行，`job_kill` 报「没有这件作业」，而两者都不是真话。
//
// 进程内那台实现仍在 [github.com/snight1983/ds-harness-go/jobs/localjobs]，
// 单进程部署照旧用它。两台在装配面上是可以对着换的（见 [Config]）。
//
// # 账本共享，执行不共享
//
// 这是理解本包每一处分岔的那一条。一件作业有两样东西：
//
//   - **它的记录**——id、种类、标签、属主、状态、结局。落在域表上，任何副本
//     任何时候都读得到，也因此可以被任何副本判断、被下一次进程接管。
//   - **它的执行资源**——[github.com/snight1983/ds-harness-go/jobs/jobs.Hooks]
//     里那三只手。它们是起这件活儿的那次调用交回来的闭包，只存在于那个进程的
//     内存里，没有任何办法序列化到表上。
//
// 于是 [Registry.List] 和 [Registry.Get] 在每个副本上都给出同一个答案，而
// [Registry.Read]（活着时）和 [Registry.Kill] 只有那个执行副本办得到，别的副本
// **报错**，错误里点名它在哪个 [github.com/snight1983/ds-harness-go/jobs/jobs.RunnerID]
// 上。不假装成功：一个调用方以为自己停掉了一件其实还在跑的活儿，比一句「这儿办不了」
// 坏得多。
//
// # 记录先于活儿
//
// [Registry.Start] 先把一条 running 记录条件写进账本，再去调
// [github.com/snight1983/ds-harness-go/jobs/jobs.Start.Run]。反过来的话，两步之间
// 崩一下就有一件跑着的活儿在账本上不存在——没有任何副本知道它、知道该去停它。
// 反过来的代价只是一条孤儿记录，而那是收得回来的：活儿没起来就当场删掉，进程没了
// 就由下一次启动接管（见下一节）。
//
// # 发号不靠共享计数器
//
// id 仍旧是 `<种类>-N`。号是这样抢的：读一次全表，取这一类当下的最大序号，然后对
// `<种类>-<最大号+1>` 那把键做一次条件写（[github.com/snight1983/ds-harness-go/storage/domain.Table.Create]）。
// 撞车就是「另一个副本刚好也在开这一类的活儿」，重读重试。
//
// 换成一个共享计数器的话，每一次开工都要抢同一个全局槽，那是一处天然的热点；
// 而条件写只在真的撞上同一个号时才重来。
//
// # 启动时接管
//
// [New] 会扫一遍全表，把盖着**自己这个** runner、状态却还是 running 或者 stopping
// 的记录判成 failed。这样的记录只有一个来历：上一次这个副本的进程没了。不接管的话
// 它们永远挂在 running 上，一直占着属主的并发名额，而没有任何一个副本会去动它们。
//
// # 并发上限是跨副本的
//
// [Config.MaxConcurrentJobsPerOwner] 数的是账本上这个属主所有活着的作业，不分它们
// 在谁那儿。上限护的是那个属主（别让一个会话把资源吃光），不是那台机器。
//
// # 本轮画出来的两条边界
//
// 这两件事**不做**，是决定，不是遗漏：
//
//   - **跨副本的变更通知**。[Registry.OnJobDone]、[Registry.OnJobsChanged] 和
//     [Registry.AttachController] 都是**副本本地**的：它们挂在这个进程的作用域上，
//     也只收得到这个进程发出的通知。B 副本结算了一件属于本地某个属主的作业，
//     这里一声不响。要补这一条得有一套发布订阅，那是另一件事。
//     和 [github.com/snight1983/ds-harness-go/storage/domain.Changed] 那条边界同源。
//   - **账本的保留策略**。终态记录会一直留在表上：属主释放和服务释放都不删它们
//     （见 [Registry.disposeOwned]），因为一条终态记录是别的副本唯一还能读到这件
//     活儿结局的地方。谁来清、留多久，本轮没有答案。
