// Package jobs 是后台作业那条**服务缝**：作业 id、按会话围起来的访问、生命周期
// 状态、完成监听器和属主清理这几条契约归它，而干活那些资源仍旧归生产方自己。
//
// 对应 DSH 的 @deepseek-ai/dsh-jobs（packages/jobs/jobs）。
//
// 源: packages/jobs/jobs/src/index.ts:1-7
//
// 进程内那台实现在 ds-harness-go/jobs/localjobs。
//
// # 实现方必须守住的几条
//
//   - 登记活得比生产方和控制器那些协程都长。属主释放和服务释放会取消活儿并等着
//     守规矩的生产方；取消那一下自己出错时只强行把那条记录判失败。属主释放那条
//     路还要把记录标成已汇报——它的属主正在被拆掉，已经没有读者了。
//   - 有主作业的访问由属主的会话 id 围起来。id 是可预测的，所以边界是**授权**，
//     不是保密。
//   - 结算先到先得：一条终态记录、放开所有等待者、一轮被包住的监听器通知，哪怕
//     生产方的结局来得更晚也一样。完成放在最后announce，等记录提交、其余每一个
//     观察者都看过之后——因为一个汇报方可能当场就开一个模型回合。
//   - [Registry.Start] 在没有任何已挂上的作业控制器服务这个属主时拒绝开工，
//     这样生产方就不会起一件属主既收不走也停不掉的活儿。
//
// # 新增: 可见范围由 scope 决定，不是「整个进程」
//
// DSH 那两个监听器和控制器的可见范围由「登记它的那个 cordis 上下文的作用域」决定：
// 从无作用域上下文登记的服务每一个属主，从某个 agent 组合的作用域下登记的只服务
// 组合在它底下的那些 agent。Go 这边同一条规则由
// [ds-harness-go/core/scope.Admits] 直接给出：登记时交进来的那个 *scope.Scope
// 就是标签，属主 agent 自己那把作用域钥匙就是分派键。
//
// # 新增: 这条缝是一个接口，不是一个抽象类
//
// DSH 那个抽象类的构造函数里有一道 `new.target === JobRegistry` 的守卫，因为
// `abstract` 在运行期会被抹掉，一份写错的组装表会登记出一个方法全空的 ctx.jobs。
// Go 的接口压根实例化不了，这道守卫因此没有对应物。
