// Package localjobs 是后台作业那条缝的**进程内实现**：每一条记录都在内存里，
// 交出去的永远是新造的快照，绝不是活状态。
//
// 对应 DSH 的 @deepseek-ai/dsh-jobs-local（packages/jobs/jobs-local）。
//
// 源: packages/jobs/jobs-local/src/index.ts:1-10
//
// 契约（属主、隔离、生命周期）写在 [github.com/snight1983/ds-harness-go/jobs/jobs] 那一侧，本包只讲
// 它是怎么被守住的。
//
// # 登记活得比生产方和控制器都长
//
// 属主释放和服务释放都会取消活儿、等到守规矩的生产方结算，再把记录摘掉；取消
// 那一下自己出错时只把那条记录强行判失败，并报出「活儿可能变成孤儿」。
//
// # 新增: 这台注册表是并发安全的
//
// DSH 是单线程 JS，那份 store 没有任何保护——一次结算和一次 list 不可能同时发生。
// Go 这边生产方在自己的协程里结算，模型侧的调用来自另一条，所以整张表由一把
// [sync.Mutex] 罩着。由此多出来的规矩只有两条，别处都和 DSH 一模一样：
//
//   - **监听器一律在锁外跑**。一个观察者回头调 [Registry.List] 是完全正常的事，
//     在锁里通知就是自己等自己。所以每条路都是「锁里改完、拿到该通知谁、放锁、
//     再通知」。
//   - **调生产方也在锁外**。[Registry.Kill] 和拆除都会调 [github.com/snight1983/ds-harness-go/jobs/jobs.Hooks.Cancel]，
//     而那一下可能让生产方当场结算；结算要拿同一把锁。放锁调完再回来，回来时
//     必须重新确认这件作业还没落定——DSH 单线程下不存在的那个窗口，Go 这边存在。
//
// # 新增: 「等结算」是一个关掉的 channel，不是一组 resolver
//
// DSH 给每个等待者往 `waitResolvers` 里塞一个 resolver，超时和中止各自把自己那个
// 摘掉。Go 里每件作业带一个结算时关掉的 channel，所有等待者一起被放开，摘不摘由
// select 自己解决，那张表因此不存在。仍旧保留的是**等待者计数**：结算那一刻只要
// 还有人在等，这件作业就当场标成已汇报，好让紧接着跑的完成汇报方不再多发一次通知。
