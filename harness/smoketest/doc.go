// Package smoketest 拿一棵**已经装好的** agent 树，驱一整轮，把最终那句话和这一轮
// 的 token 记账交回来。它验的是「装得起来、跑得完一轮、关得干净」这条链本身。
//
// 对应 DSH 的 @deepseek-ai/dsh-loader-smoke（packages/test-support/loader-smoke）。
//
// 源: packages/test-support/loader-smoke/src/agent-turn.ts:1-4
//
// # 和 harnesstest 的分工
//
// [github.com/snight1983/ds-harness-go/harness/harnesstest] 交出的是循环的先决依赖，
// 停在循环之前；本包站在另一头，要求那棵树**已经装完并且公布过**——恰好一个顶层
// agent、模型路由上有适配器、循环已经登记。两件事各在一条线的两端，所以不合成
// 一个包。
//
// # 子进程那一半为什么不在
//
// 上游那台冒烟机真正启动的是一棵 cordis.yml 装出来的树：起一个子进程、按
// DSH_EXAMPLE_MODE 在「tsx 跑 src」和「node 跑 lib」之间二选一、关掉 stdin、
// 等一个干净的退出码。这三件事在 Go 里一件都不存在——没有 Loader，没有那份
// 配置文件，编出来就一个可执行文件、没有源码态与构建态两条启动路径。
//
// 剩下的那一半——「驱一轮、收最终文本和用量」——和宿主是不是子进程无关，
// 那才是本包。
//
// 新增: 上游 runFixtureTurn 的入参是一份已经settle 的 cordis 上下文，agent 注册表
// 和会话存储都从它身上取。Go 里没有那张服务表，所以摊成 [Deps] 三个显式字段。
//
// # 不做什么
//
//   - **不装配。**那棵树谁装的、装了些什么，是调用方的事；本包只要求它已经能跑。
//   - **不登记模型适配器，也不编排模型行为。**一次冒烟要模型说什么，
//     由调用方自己那条流规则或者假适配器决定。
//   - **不起子进程，不认配置文件。**理由见上。
//   - **不做断言。**它交回一份结果，验什么由用例自己写——把断言写死在这里，
//     等于替每一个调用方决定什么叫「跑通了」。
//   - **不管拆除。**装的人拆，本包一件东西都不持有。
package smoketest
