// Package harnesstest 交出一副**循环的先决依赖**：模型运行时、会话存储、系统提示词
// 注册表、工具运行时、agent 注册表，以及托着它们的那个作用域。它刻意**不造循环**。
//
// 对应 DSH 的 @deepseek-ai/dsh-agent-loop-testkit（packages/test-support/agent-loop-testkit）。
//
// 源: packages/test-support/agent-loop-testkit/src/index.ts:1-6
//
// # 为什么停在循环之前
//
// 这一层的用处全在那句「不造循环」上。要验的东西多半是**循环怎么装起来**——
// 装两次会不会撞、造法登记失败时前面那几样拆不拆得干净、某一样缺席时报的是不是
// 那句话。这些用例要自己捏着装载顺序，一个连循环一起装好的脚手架把它们要验的那
// 一步替它们做掉了，剩下的只有一个已经装完的成品。
//
// 想要连循环一起的那份成品，那是
// [github.com/snight1983/ds-harness-go/harness.New]——它是生产装配，不是脚手架。
//
// # 谁拥有这些东西
//
// 交回来的每一样都是构造函数的返回值，没有一样藏在包级变量里，所以同一个用例里
// 立两副互不相干。释放走 [Dependencies.Dispose]；传了 *testing.T 的那条路
// （[Mount]）已经挂上 t.Cleanup，不必再自己收。
//
// # 不做什么
//
//   - **不造循环，也不登记 agent 造法。**理由见上。
//   - **不接存储后端和持久化。**这两样各要一个真的介质；要验持久化的用例自己
//     捏一份假的交进去，本包不替它猜接哪一个。
//   - **不装任何工具。**交回来的工具运行时是空的——一个用例要哪几件工具，
//     只有它自己知道。
//   - **不登记模型适配器。**同上：假适配器的行为是用例要编排的东西，
//     写死一个只会让它先把那个拆掉。
