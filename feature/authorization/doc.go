// Package authorization 是「让人当场把一条凭据授权下来」的那条缝：插件登记一条
// 流程说自己怎么拿到某条凭据，界面登记一半说自己怎么跟人说话，本包把两半接起来
// 并保证同一条凭据同一时刻只有一次尝试在跑。
//
// 源: packages/credentials/authorization
//
// # 它解决的问题
//
// 一条 OAuth 凭据不是配出来的，是**跟人来回几趟**换出来的：打开一个页面、敲一个
// 短码、等回调、轮询令牌。这几趟里，知道该怎么走的是插件，能跟人说上话的是界面，
// 而两者互相不认识——插件不知道此刻是哪个页面在看，界面不知道这条凭据要走几步。
//
// 本包就是那个中间人。它不知道任何一条流程怎么走，也不渲染任何一个问题；
// 它管的是三件事：谁认领哪条凭据、同一时刻只许有一次尝试、一次尝试怎么算结束。
//
// # 三个角色
//
//	[Flow]         一个插件关于「怎么拿到某条凭据」的知识，登记进来。
//	[Interaction]  一个界面关于「怎么把话摆到人面前」的知识，跟着请求交进来。
//	[Session]      本包交给跑起来的流程的那一套：说话、留脚印。
//
// [Interaction] 跟着请求交而不是登记进来，是因为起这次授权的那一位才是能跟人说上
// 话的那一位——问题因此正好落到问出它的那个页面上。
//
// # 写是流程自己做的
//
// [Flow.Run] 正常返回意味着那条凭据记录已经**由流程自己**经凭据提供方提交过了。
// 本包不碰那个值，只核实两件事：这次尝试之内观察到过一次提交（订阅记录变更），
// 而且尝试结束之后那条记录还在（[Credentials.DescribeRecord]）。两条都过才报
// [StatusAuthorized]，否则是 [CodeNotCommitted]。
//
// 让流程自己写，是为了让一个用自己那套存储适配器落盘的库仍然是唯一的写者，
// 而不是把值誊一遍再写第二遍。
//
// # 和 DSH 的分歧：尝试落在介质上
//
// DSH 的一次尝试活在一个 Promise 里，单飞槽位是一个内存 Map，所以它只有两种状态：
// 在跑，和不在。它的文档自陈「flow 不可恢复」，理由是浏览器进程说没就没。
//
// 本仓库的前提不一样：一个人可以干到一半走人，第二天接着干；一次授权可以起在这个
// 副本上、接在那个副本上。所以一次尝试是介质上的一条记录（[Attempt]），
// 于是多出第三种状态——**记录还在，跑它的那个进程没了**：
//
//	在跑（[Entry.InFlight]）    有副本攥着一份没过期的租约
//	停着（[Entry.Stalled]）     记录在，没有副本攥着
//	没有                        这个键上一条记录都没有
//
// 停着的那一种既不是忙也不是闲，所以 [Service.Begin] **拒**掉它（[CodeStalled]），
// 让调用方明确选 [Service.Resume] 还是 [Service.Cancel]——起一次新的会把上一次攒下
// 的进度悄悄扔掉。
//
// # 接手是从头再跑一遍
//
// 一个 async 闭包序列化不了，所以「接着上次干」不可能是恢复一个续体。本包的做法是
// 重跑 [Flow.Run]，由流程自己读回上一次留下的脚印然后跳到那一步：
//
//	[Session.Checkpoint]  把「我走到哪儿了」写进介质，顺带续租、顺带读回撤销
//	[Session.Resumed]     读回上一次写下的那份；头一回跑是 nil
//
// 一次 OAuth 在把人支去浏览器**之前**记下 state 和 verifier，接手的副本于是直接
// 跳到轮询令牌那一步，而不是从头再要一次授权码。本包不解释脚印的内容。
//
// # 单飞是怎么保证的
//
// 记录键就是凭据键，所以「一个键上只有一次尝试」是介质自己保证的：
//
//	[Service.Begin]   [github.com/snight1983/ds-harness-go/storage/domain.Table.Create]，键已存在就输
//	[Service.Resume]  [github.com/snight1983/ds-harness-go/storage/domain.Table.Update] 的条件写，两个副本抢，只有一个赢
//
// 攥着它的副本每隔租期三分之一续一次租（[Attempt.HeldUntil]）。租约断了别的副本
// 就能接手；而原来那个副本在下一次续租时读到别人的 Holder，于是停手且**不结算**
// （[CodeTakenOver]）——那条记录已经是别人的了。
//
// # 撤销要写下去
//
// 撤的那一位和跑的那一位可能不在同一个进程里，所以 [Service.Cancel] 写的是
// [Attempt.Cancelled] 这个标记。攥着它的副本在下一次续租、发问或者留脚印时读到它，
// 然后自己走结算那条路。没人攥着的时候（一次停着的尝试）就地收掉。
//
// # 结算的两个口径
//
// 起这次尝试的那一位从 [Service.Begin] 的返回值就知道结果了，两种：
// [StatusAuthorized] 和 [StatusCancelled]，失败是以一个错误交回去的。
//
// 没起它的那些人走 [Service.OnSettled]，那里多一种 [SettlementFailed]——旁观者没有
// 别的办法把一次拒绝和一次故障分开。
//
// # 不做什么
//
//   - **不实现任何一条具体流程**。OAuth、设备码、粘贴 API Key 都是登记方的事；
//     本包一个字段都不认得。
//   - **不渲染任何界面**。[Interaction] 的两个方法由调用方实现，本包连「有没有
//     浏览器」都不知道。
//   - **不碰凭据的值**。[Notice] 和 [Prompt] 里永远不含密钥，本包也从不读记录内容
//     ——它只问 [Credentials.DescribeRecord] 那条记录在不在。
//   - **不自动重试，也不自动接手**。一次停着的尝试要人（或运维口径的调用方）明确
//     选接手还是撤掉，理由见 [CodeStalled]。
//   - **不管流程之间的顺序**。两条凭据要按什么次序授权是装配方的事。
//   - **不做记录级的条件删除**。[github.com/snight1983/ds-harness-go/storage/domain.Table.Delete] 是无条件的，本包靠「只在还攥
//     着租约时才走到那一步」代替，见 [Service.release] 那段说明。
