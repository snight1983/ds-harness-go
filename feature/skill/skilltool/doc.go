// Package skilltool 把技能目录报给模型，并把一份技能的完整正文送到它手上。
//
// 源: packages/skill/tool-skill
//
// 本包是 [github.com/snight1983/ds-harness-go/feature/skill] 那台注册表的**模型这一侧**。注册表回答的是
// 「这次会话有哪些技能、正文是什么」，本包回答的是「模型什么时候看得见它们、
// 看见的是哪一份、怎么把一份读进来」。
//
// # 三条通路
//
//   - **skill 工具**。模型拿一个准确的技能名调它，拿回那份 `<skill_content>`。
//   - **会话目录**。每个步骤前，把当前那份「可用技能清单」作为一条持久的用户
//     消息发布到模型可见的表面上；清单变了就整份替换。
//   - **用户明确调起**。用户自己那句话里出现 `/名字` 时，把那份技能的正文作为
//     一段注入的指令挂在这一步的末尾。
//
// # 这几条通路上守的几件事
//
//  1. **目录跟着工具的可见性走**。目录只在「这个 agent 解算到的 skill 工具
//     正是本包登记的那一个」时才发布。一次限制、或者一个同名的作用域遮蔽，
//     会把 schema 和这段调用指引一起拿掉——否则模型会拿着一份它调不动的清单。
//
//  2. **目录的身份看条目，不看那段散文**。判断要不要重新发布，比的是条目
//     摘要，不是渲染出来的 `<system-reminder>` 文本；那段框架是写给模型看的，
//     不该参与「变没变」这个判断。
//
//  3. **`/名字` 这个手势只认用户自己说的话**。只扫来源是 [llm.SourceUser] 的
//     消息，外部文本伪造不出这个手势。
//
//  4. **认不出来的目录记录当成「不是本包的目录」**，不抛错。日志可能是恢复的、
//     分叉的、或者外部写进来的，种子校验只保证 source 是个带非空 kind 的对象。
//     在步骤监听器里抛错会让那个会话之后每一个回合都失败。
//
// # 不做什么
//
//   - **不拥有技能从哪来。**清单怎么收、同名谁赢、正文怎么渲染，全在
//     [github.com/snight1983/ds-harness-go/feature/skill] 那台注册表上；本包只是它的模型这一侧。
//   - **不读磁盘。**正文是提供方交过来的值，本包的依赖里没有
//     [github.com/snight1983/ds-harness-go/fs] 那条接缝——技能来自打包、本地目录还是远端注册中心，
//     是提供方要回答的问题。
//   - **不为技能正文作保。**它是模型读完照着做的话，不是一份权柄：调得动哪些工具，
//     仍由 [github.com/snight1983/ds-harness-go/tools] 那张注册表和作用域上的限制说了算。
//   - **不管这些文字占掉多少上下文。**目录和正文进了模型表面之后，计量归
//     [github.com/snight1983/ds-harness-go/feature/tokenmeter]，装不下时怎么办归
//     [github.com/snight1983/ds-harness-go/feature/compaction]。
