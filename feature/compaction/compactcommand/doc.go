// Package compactcommand 是 `/compact` 这条面向人的斜杠命令。
//
// 源: packages/compaction/command-compact（@deepseek-ai/dsh-command-compact）
//
// # 它是什么
//
// 一层薄薄的适配：把人敲下的那一行 `/compact` 翻成
// [github.com/snight1983/ds-harness-go/feature/compaction.Engine] 上的一次
// CompactNow，再把结局排成一句人读的话。它不挑区间、不做摘要、不写一条事件——
// 那三件全在压缩接缝那一侧。这一层只管两件事：这行字合不合法，以及这个结局
// 该怎么说。
//
// 语法只有一条：**不带参数**。`/compact 最近十条` 一律回一句用法提示，因为
// 「压哪一段」不是这条命令能表达的东西——指定区间那条路是
// CompactRegion，而它不是给人敲的。
//
// # 它是那道接缝的第三个入口
//
//	   压力线到了 ──▶ feature/compaction/basic ─┐
//	提供方说超窗了 ──▶ feature/compaction/basic ─┼─▶ compaction.Engine ─▶ 会话
//	    人敲 /compact ──▶ 本包 ─────────────────┘
//
// 三条路共用同一把**持久**锁：一条 compaction/start 一直持有到 compaction/end。
// 所以自动的正压着的时候人敲 /compact，回的是 busy；反过来也一样。这一层不再
// 自己加一把锁，加了只会多出一种「本进程说忙、日志说不忙」的不一致。
//
// # 六种回话，外加两种
//
// 预期之内的失败由接缝分好类交上来（compaction.ManualError 的 Code），
// 这一层照着那张封闭的单子挑一句话：
//
//	busy         这个进程有一次压缩正开着，或者这个 agent 不空闲
//	cancelled    做完之前被撤回了
//	changed      选中的那一段在被换掉之前变了
//	summary      摘要那一步没做出有用的东西
//	commit       替换落到表面上那一步没干净地结束
//	persistence  压完了，但是会话没存下来
//
// 另外两种不是失败：一段还没有可压的历史回一句成功，
// 一次压成了回「压掉了几条、大约省下多少 token」，并且指向那条 compaction/summary。
//
// 剩下的一切——一个认不得的分类码、装配没接对、后端自己炸了——原样抛给调用方。
// 那些不是「这次没压成」，是这套东西装错了或者坏了，把它们说成一句给人的提示，
// 等于把一次故障藏进一句客气话里。
//
// # 摘干净再摘下来
//
// [Controller.Install] 交回的那个摘除函数**先注销、再等**：注销之后不会有新的
// /compact 进来，然后它等已经进去的那几次跑完。反过来先等再注销，等的过程中
// 还能再进来一条，那个等就永远等不完。
//
// # 不做什么
//
//   - **不挑区间，不做摘要，不写事件。**这三件归
//     [github.com/snight1983/ds-harness-go/feature/compaction] 那道接缝和它的后端；
//     本包一个字节的会话状态都不碰。
//   - **不自己加锁。**并发由那条持久的 compaction/start 挡着，本进程再加一把
//     只会多出一种「本进程说忙、日志说不忙」的不一致。这里那点计数是为了
//     摘除时等干净，不是为了互斥。
//   - **不认参数。**`/compact` 后面跟任何东西都回用法提示；要指定区间得走
//     CompactRegion，而那不是一条给人敲的命令。
//   - **不收图片。**定义里没有输入描述符，所以带图的调用在注册表那一层就被判掉了，
//     图留在编辑器里。
//   - **不把故障说成提示。**只有那六个分好类的失败会变成一句回话，其余原样抛出。
//   - **不拥有事件流，也不折任何投影。**[RegisterInvariants] 装进去的那份检查是
//     **空**的：那对配平的持久标记归压缩接缝验，登记与派发的生命周期归命令注册表验，
//     登记只是为了让「检查过了、结论是无需检查」和「这个包被漏掉了」区分得开。
package compactcommand
