// Package agentpresets 是「一个会话的模型可见能力从哪一份组合来」这件事。
//
// 对应 DSH 的 @deepseek-ai/dsh-agent-presets（packages/preset/agent-presets）。
//
// 源: packages/preset/agent-presets/src/index.ts:1-22
//
// 一份预设是磁盘上的一个目录：目录名就是它的 id，里面一份 agent.cordis.yml 是它的
// 组合清单，旁边可以再放一份 preset.yml 装展示文字。发现是**不记忆的**——每次
// List/Resolve 都重扫一遍根目录，于是进程跑着的时候新写出来的预设当场就在名单上。
//
// 一份预设**只装一次**，装在一个常驻作用域上；每个点了它名字的 agent 通过把自己的
// 作用域钥匙认那个常驻钥匙作父来「加入」。这就是为什么它是一份组合而不是每个会话
// 一份：那些插件实例、工具登记、提示词段落只存在一次，会话之间的区分由插件自己
// 按会话键着（它们比预设早，本来就是为一个共享世界写的）。一个手上没有 agent 的
// 宿主读者——一次冷读转写稿——也能用同一把常驻钥匙解算到同一批登记。
//
// # 这里没有照抄的部分
//
// **新增: 装载那一半整个换掉了。** DSH 的 mount.ts 是 cordis 那台**动态模块装载器**：
// 它照着 YAML 里的行 `import()` 一个个 npm 包，再靠 Fiber 树、EntryTree、
// ctx.reflect.store 那套反射去审计装出来的子树。Go 是静态链接的，运行期没有
// import 这回事，那台装载器在这门语言里不存在。
//
// 换成的是一张**组装器名册**（[Composer] / [ComposerSet]）：宿主在编译期把带名字的
// 安装函数登记进来，组合清单里的一行就是「按这个名字取一个安装函数，把这段 config
// 交给它，让它装到常驻作用域上」。可观察的契约一条不少：
//
//   - 一份预设一个常驻装载，被点了它名字的每个 agent 共享（单飞 + 文件戳换代）；
//   - 任何一行装不起来（名字不认识、安装函数报错），整份装载回滚，一行都不留；
//   - agent 靠 [github.com/snight1983/ds-harness-go/scope.BindParent] 加入，靠
//     [github.com/snight1983/ds-harness-go/scope.ParentBinding.Rebind] 改嫁。
//
// **新增: DSH 的 leakedServices / inactiveRows / serviceForAgent 不移。** 它们审计的是
// cordis 的服务领域（realm）：一行插件把服务发布进**根领域**就变成了进程级的，
// 第二个会话装同一份预设时会撞上第一个。Go 这边没有那个隐式的根领域——
// 一次登记要显式地把持有者作用域**作为参数传进去**（`Register(ctx, owner, ...)`），
// 所以一个装在常驻作用域上的组装器**在结构上够不着根**。那条不变量在这个设计里
// 违反不了，于是它在 [RegisterInvariants] 里是一条写明了理由的空检查，而不是漏掉的。
//
// **新增: 文件系统直接走 os，不走 [github.com/snight1983/ds-harness-go/fs] 那道接缝。** 那道接缝建模的是
// **执行世界**——模型看得见、可能是个远端容器的那个文件系统。预设根不是执行世界，
// 它是这台 harness 自己的部署配置。把两者混起来，等于让一个被沙箱关着的会话去决定
// 这台 harness 组装哪些插件。DSH 在这个包里也是直接用 node:fs 的，同一个理由。
//
// **新增: dsh-home-paths 那条 OUT_OF_SCOPE 的口径这里照旧。** DSH 用
// `dshHomePath(USER_PRESET_DIR)` 从本机 home 算出可写根，服务端没有「当前用户的
// home」，所以 [Config.UserRoot] 是一条由装配方给的绝对目录，留空表示这套部署
// 不给本地创作留位置。[UserPresetDir] 仍然导出，装配方要拼那个约定名字时用它。
//
// # 这个包守的四条
//
//   - **坏掉的预设留在名单上，但装不了。** 藏起来的话，那个目录仍旧占着 id——
//     复制路径拒绝这个名字，而界面上没有任何东西可看、可删。
//   - **展示文字坏了绝不致命。** 名字读不出来的预设照样装得起来，只是显示它的 id。
//     展示不是能力，一个坏名字不该变成一个起不来的 agent。
//   - **创作只写 user 根，而且只有整目录复制这一种写。** 没有任何调用方能递进来
//     一段组合文本，于是创作授不出被复制的那份预设本来没有的能力。
//   - **会话真正跑在哪一份上要读日志，不能只读创建头。** 头记的是「建的时候点的
//     是哪个」，而一个还空着的会话可以换预设，换完之后的每一轮都跑在新的那份上。
//     见 [ResolveSessionPreset]。
