// Package goal 是挂在会话日志上的同会话目标：一条完成目标、它的耐久阶段，
// 以及那份**从不落盘**的续推资格。
//
// 源: packages/goal/goal/src/index.ts
//
// # 这个包在守什么
//
// 目标的唯一事实是会话日志里那一串 `goal/change` 事件。每一条都带着改完之后的
// **完整快照**，不是增量——于是目标状态完全不依赖收件箱怎么排、谁认领了哪一条，
// 一段日志放在哪里折出来都一样。
//
// 每一次耐久改动把修订号加一。调用方要改就得交出它以为的那个修订号
// （[Ref]），对不上当场拒掉（[CodeStaleRevision]）。这条 compare-and-set 是唯一
// 挡住「两个持有方各拿着一份旧状态、后写的把先写的抹掉」的东西。
//
// # 阶段和活化是两条轴
//
//   - [Phase] 是耐久的：active / paused / blocked / complete，落进日志，回放得出来。
//   - [Activation] 是进程局部的：armed / disarmed，**一次都不落盘**。
//
// 分成两条轴是因为它们回答的是两个问题。阶段回答「这个目标本身还成立吗」，
// 活化回答「**这个进程**此刻可以自动往下推它吗」。续会话、分叉、换驱动都保留
// 阶段、修订号和已用轮数，但活化一律回到 [Disarmed]——要动起来必须有人显式再
// [Service.Resume] 一次。[Service.Install] 挂的那条会话起跑边是这句话的兑现处。
//
// 「不是本进程写的那条 goal/change 一律打回 disarmed」是同一条规矩的另一半：
// 一次分叉、一段被别的进程续上的日志，都不该让这里自己动起来。
//
// # 轮数是怎么算出来的
//
// [View.RoundsStarted] 不是一个被写下来的数，是从日志里数出来的：只有**带着
// [Source] 这份来源**的 user/message 才把它往上推，普通的人类回合一次都不算。
// 那份来源因此是「这一轮是目标推的」唯一的耐久证据，而 MaxGoalRounds 是一道
// 数得出来、赖不掉的预算。
//
// # 两套折日志的标准，别混
//
//   - [Fold] / [ApplyEvent] 是**严格**的：验跃迁、验键集、一个字节都不放过。
//     它是 [ValidateStream] 那条不变量的判据，也是 [Service] 每一次改动之前
//     据以判断的那份状态。
//   - [ApplyProjection] 是**宽松**的「最后写的赢」：读不动就原样返回。它服务的是
//     一份要落盘做检查点的投影，而一个读不动的历史事件不该让整份投影再也建不起来。
//
// 两者的标准之所以可以不一样，是因为写的那一侧已经验过了：一条改动落进日志之前
// [Service] 先折过一遍，[ValidateStream] 在装配方装上它的地方还会再拒一次。
//
// # 装配
//
// 这个包的事件类型要加进会话词汇表，否则读日志的一方会认为它读到了一条
// 不认识的必需事件：
//
//	vocabulary := session.CoreVocabulary().With(goal.EventTypes()...)
//
// 三件可选的接线各自独立，缺哪一件别的照跑：
//
//   - [Service.Install] 挂会话起跑那条边，[Activation] 靠它归零。
//   - [RegisterProjection] 把 `goal` 这个投影单元登进投影注册表。
//   - [RegisterInvariants] 装上那条整流检查。装上它之后，装配方要负责在一条
//     `goal/change` 或者一条带目标来源的 user/message **落盘之前**把待写的那条
//     事件接在末尾再交进来——少了这一步，破规矩的改动会先落进日志，等下一次装载
//     时才炸，那时候它已经改不掉了。
//
// # 错误分两种语言
//
// [Error] 的 Message 是**给模型看的**，所以是英文，而且逐字照抄 DSH：这句话会
// 经由 goal 那几件工具原样变成工具结果，是模型据以改写下一次调用的唯一线索。
// [FoldError] 的 Reason 相反，它说的是「日志坏了，坏在哪条不变量上」，那是只有
// 读日志的人才用得上的话，所以是中文。
