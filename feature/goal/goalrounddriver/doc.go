// 本包的作用：把一个还点着的目标自动往前推——agent 一转空闲就给它递一条
// 「接着干」的续推提示词，一轮接一轮，直到目标完成、被停住、或者撞上它自己那个
// 轮数上限。
//
// 源: packages/goal/goal-round-driver/src/index.ts
//
// # 它凭什么敢自动发话
//
// 只凭一样：[github.com/snight1983/ds-harness-go/feature/goal.View] 上那个进程本地的 [goal.Armed]。
// 目标本身是耐久的，活化不是——重启之后每个目标都是 [goal.Disarmed]，谁都不会
// 因为一段旧日志被自动推起来。本包装上去的第一件事就是把已经在场的 agent 一律
// 打回原形（见 [Install]），为的正是不从上一个生产方那里继承一份看不见的授权。
//
// # 为什么这套状态机看着这么啰嗦
//
// 因为「递一条提示词」这件事从提出到落进日志之间隔着四道边界，每一道都可能被
// 别人抢在前面：
//
//   - 排队（queued）：消息进了收件箱，但驱动还没认领；
//   - 认领（claimed）：驱动为某个步骤把它取走了，但步骤还没进；
//   - 准入（admitted）：它作为一条 user/message 落进了日志，这一轮才真的算数；
//   - 而这中间人可以随时发一条自己的话、可以取消、可以改目标、可以停掉它。
//
// 所以本包为每个 agent 记一份 [roundAttempt]，并且在每一道边界上都重新问一遍
// 「我预定的那一轮此刻还成立吗」。任何一处对不上就**认输**——撤掉预定、把那条
// 目标停住或者打回未活化，而不是硬把提示词塞进去。宁可少推一轮，也不能让模型
// 收到一条它已经不该收到的指令。
//
// # 并发
//
// 新增: DSH 跑在单线程事件循环上，那些处理器和 drive() 之间不会交错，所以它那份
// DriverState 是裸字段。Go 这边观察者跑在「谁追加了事件谁就跑」的那条协程上，而
// 驱动自己是另一条协程，两边真的会同时动同一份状态。于是本包给每份状态配一把
// 互斥锁，并且立下一条规矩：**锁绝不跨过一次会阻塞的调用**——落盘检查点、
// [goal] 那几个改状态的方法、以及 [agent.Agent.Followup] 一律在锁外调。
