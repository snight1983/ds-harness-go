// Package workflow 是编排工作流这条能力接缝：一段编排脚本怎么开工、怎么结清，
// 以及它跑的过程中往外说些什么。本包**只有契约**，一行编排都不跑。
//
// 源: packages/workflow/workflow/src/index.ts
//
// # 一次工作流运行是什么
//
// 一段脚本，加上它的一份身份说明，交给引擎；脚本里可以反复调 agent(...) 扇出
// 子 agent，可以用 phase(...) 给进度分段，可以用 log(...) 说话；跑完了交回一个
// JSON 值。调用方拿到的是一个**活的运行句柄**——问它要结果、取消它、处置它。
//
//	调用方 ──Start(脚本, meta, args, 父 agent)──▶ 引擎
//	                                              │
//	  ┌───────────────────────────────────────────┤ 一路发这六条边
//	  │  workflow/start ─ phase ─ log ─ agent-start ─ agent-end ─ end
//	  ▼
//	观察方（界面、遥测、审计）
//
// 六条边只观察：它们**看不到**那个运行句柄，所以一个观察者不可能取消别人的运行。
// 这是这条接缝上最要紧的一条分工。
//
// # 这个仓库里没有引擎
//
// DSH 那边唯一的引擎实现是 packages/workflow/workflow-worker-thread：它跑的是
// JavaScript 编排脚本，载体是一条 Node worker 线程。这两样本仓库都没有，那个包
// 因此裁了不需要，它唯一的消费方 packages/workflow/tool-workflow 跟着一起裁掉。
//
// 新增: 于是本包在这个仓库里是一条**只有契约、没有产出方**的接缝。留着它有两个
// 理由。一是这套词汇是引擎和观察方之间的约定，而观察方（界面、遥测）是可以先于
// 引擎存在的——把词汇定在这里，将来补一个 Go 引擎不必反过来推翻已经装上去的
// 观察者。二是 [github.com/snight1983/ds-harness-go/feature/workflow/toolralph]
// 那件 Ralph 工具在 DSH 侧正是挂在这条接缝上的，它在本仓库改写成了一个写死的
// for 循环（理由见那个包的包文档）；这条缝在不在，决定的是「以后能不能把它接
// 回来」，不是「今天它能不能跑」。
//
// 这件事在账本里记着，不是遗漏：`docs/portmap/rulings.md` 里 `workflow/` 那一节
// 四条裁决写了引擎和脚本工具为什么出局、接缝为什么留下。
//
// # 装配
//
// 引擎实现方自己攥一个 [NewLifecycle] 造出来的 [Lifecycle]，在该发边的地方调它
// 那几个 Emit 方法；宿主把那同一个 [Lifecycle] 交给观察方去登记，并且可以调
// [RegisterInvariants] 把这条接缝自己那份配对检查装上。
//
// # 不做什么
//
//   - **不跑脚本。**解析、沙箱、并发上限、取消传播全归引擎实现；本包连一个
//     [Engine] 的实现都没有。
//   - **不开子 agent。**脚本里那个 agent(...) 最终落到
//     [github.com/snight1983/ds-harness-go/feature/subagent] 上，本包只在事件负载里
//     记下孩子的 id，从不派活儿。
//   - **不校验 meta 和脚本。**「meta 形状对不对」是引擎在脚本正文跑起来之前的活儿；
//     本包只把 [CodeMetaInvalid] 这类码定下来，好让两边说同一种话。
//   - **不持久化。**运行、事件、结果一律不落盘。要留痕的观察方自己往会话日志或者
//     遥测里写。
//   - **不给观察者控制权。**六条边都是既成事实的通告，负载里没有运行句柄，
//     观察者的返回值和 panic 都改变不了那次运行。
//   - **不定义脚本里那套 API。**agent()、phase()、log()、parallel()、pipeline()
//     是脚本领域的词汇，归引擎；本包只认它们发出来的那几条边。
