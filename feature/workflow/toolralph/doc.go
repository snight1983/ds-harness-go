// Package toolralph 是那件面向模型的 Ralph 工具——朝着一个**不可变**的目标反复推进，
// 每一轮开一个全新的子 agent，轮与轮之间只让一份有界的结构化交接过去。
//
// 源: packages/workflow/tool-ralph/src/index.ts
//
// # 什么是 Ralph
//
// 一个人做一件长活儿，做着做着上下文就脏了：早先那些试错、走岔的路、已经作废的
// 假设，全堆在同一段对话里，越往后越挤，也越容易把自己绕进去。Ralph 的答案是
// **每一轮换一个人**：新那个孩子看不到父的对话，也看不到上一个孩子的会话，它只
// 拿到两样东西——那个从头到尾一个字都不变的目标，和上一轮留下的一份很短的结构化
// 报告。真正的长期记忆是那个共享的工作区（以及它当下的工作树），不是聊天记录。
//
// 于是「上下文」这件事被从「一段越来越长的对话」换成了「一个被反复检查的工作区」。
//
// # 这个包和 DSH 那一版的根本差别
//
// DSH 那边这件工具自己不写循环：它把一段**固定的 JavaScript 编排脚本**交给
// workflow 引擎（packages/workflow/workflow-worker-thread，一条 Node worker
// 线程）去跑，脚本里的 `agent(...)` 再回到子 agent 接缝上开孩子。
//
// 新增: 那条脚本引擎在本仓库里裁了 OUT_OF_SCOPE（理由见账本里 workflow/workflow
// 那条包级裁决）。它在这件事上唯一的产出就是「按顺序开几个孩子、把上一份报告带给
// 下一个」，而那在 Go 里就是一个 for 循环。所以本包把 RALPH_SCRIPT 直接写成了
// [Controller.runLoop]，没有脚本、没有 worker 线程、没有引擎。
//
// 这一步顺带去掉了 DSH 那里的**两道**校验。那边的报告要过两次同样的检查：一次在
// 脚本里（validateReport，跑在 worker 线程上），一次在宿主侧（readReport，因为
// 脚本的返回值穿过了引擎这道不受信的边界）。Go 这边没有那道边界——报告从提供方
// 手里出来直接进本包的内存——所以只留一道，见 [readReport]。
//
// # 装配
//
// [New] 收 [Config] 造一个 [Controller]，[Controller.Install] 把那件工具和那段
// 用法指引一起装上一个作用域。[RegisterInvariants] 占住这个包在不变量注册表里的
// 位置——它一条检查都不装，理由写在那个函数上。
//
// # 不做什么
//
//   - **不是工作流引擎。**那条通用的编排接缝（脚本、运行、结果、错误、事件契约）
//     在本仓库没有落地，账本里记着这个缺口；这里只有一个写死的 for 循环，不接受
//     任何外部脚本。
//   - **不拥有子 agent。**开孩子、结算、取消都在
//     [github.com/snight1983/ds-harness-go/feature/subagent]，本包只按顺序调它，并把上一轮那份
//     有界的报告交给下一轮。
//   - **不持久化进行中的轮次。**进程重启之后接不上中间状态，只能重开一次循环。
//   - **不碰工作区。**「那个被反复检查的工作区」是孩子手上的工具去读写的，本包的
//     依赖里没有 [github.com/snight1983/ds-harness-go/fs] 那条接缝。
//   - **不替孩子作证。**「完成了」和「卡住了」都是那个孩子自己说的，本包只是原样
//     转述，措辞上也刻意写成「worker reported …」而不是「done」。
//   - **不让模型改动这条循环。**轮次上限可以由模型在部署给的天花板以内挑一个，
//     除此之外提示词、schema、提供方路由、校验规则全是部署方定死的。
//   - **不处理后台化。**Ralph 是前台的：调用方一直等到有人报完成、报阻塞，或者
//     轮次用光。要后台就用普通的子 agent 派发。
