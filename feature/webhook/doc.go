// Package webhook 是外部事件进入本运行时的那条缝：一条**规则**看一次已经验过身份
// 的投递，决定要不要开一个会话——开在哪个工作区、用哪份 agent 预设、哪条模型路由、
// 哪个权限档位、第一句话说什么。运行时把规则派出去就不再管了。
//
// 源: packages/webhook/webhook/src/index.ts
//
// # 派出去就不管了
//
// [Runtime.Dispatch] 返回的时候，一件事都还没做完：它只是把当下每一条认领这个
// provider kind 的规则各起了一个 goroutine。这不是省事，是这条缝的**语义**——
// 叫它的那一位是一个 HTTP 处理器，它欠对面的是一个 202，不是一次会话创建的结果。
// 规则跑失败、会话开不出来，都只会走 [Config.Report]，不会回到 Dispatch 的调用方，
// 因为那时候它早就回复完了。
//
// 于是「这次投递到底怎么样了」这个问题，本包**答不了**。要答得了，得让规则自己
// 把结果写到它认识的地方去。
//
// # 唯一的内置动作是开一个根会话
//
// 规则可以跑任意受信任的代码，但它能让本包替它做的只有一件：开一个会话。这条边界
// 是有意的——一个能顺手调别的服务的规则运行时，会变成第二个装配层，而这个仓库里
// 装配只有一个入口（见 CLAUDE.md 的包结构一节）。
//
// 开会话是一次**有次序的事务**，见 [Runtime.Dispatch] 那条路上的 session.go：
// 先把纯校验和只读解析做完（权限档位名认不认识、agent 预设在不在、常驻组合装不装
// 得起来），再动介质（建工作区 → 造 agent → 挂会话 → 钉权限 → 起标题 → 放行提示词）。
// 动介质那一段里任何一步失败，已经做过的按逆序退回去；退回本身再失败也不会顶掉
// 原来那个错，只会另报一条。
//
// # 协作方以缝的形式交进来
//
// DSH 那个类 `inject` 了六个 cordis 服务，构造时从上下文里取。本仓库没有那张服务
// 表，所以六件事都在 [Config] 上显式交进来：拿得到具体类型的做成窄接口
// （[Workspaces]、[Agents]、[AgentPresets]、[DefaultModel]、[Permissions]），
// 接口两头对不上的做成函数（[Config.Rename]）。这么写的额外好处是本包的测试不必
// 立起半个运行时。
//
// # 关于工作区那条路径
//
// [SessionRequest.WorkspacePath] 在 DSH 那边有一条 `isAbsolute()` 校验，注释写的是
// "Existing local directory"。本仓库删掉了这条校验：这里的路径交给
// [github.com/snight1983/ds-harness-go/fs.FileSystem] 解析，而那一层背后可以是对象
// 存储——服务端没有硬盘，一条「必须以 / 开头」的断言只会把合法的后端挡在外面。
// 认不认这条路径由文件系统后端自己说了算。
//
// # 不做什么
//
//   - **不验签，也不认 HTTP。** 交进来的 [VerifiedDelivery] 名字里那个 Verified 是
//     一句**前置条件**：签名校验、请求体解析、路由、回 202，全部是叫 Dispatch 的
//     那个适配器的事（DSH 那边是 `webhook/webhook-github`）。本包只验身份字段非空
//     和事件体是不是无损 JSON。
//   - **不去重。** [DeliveryID] 只是出处，本包不拿它当去重状态。同一个 id 投两次就
//     跑两次。要去重的规则自己记账——因为「重复」的判据是业务的，不是传输的。
//   - **不管会话之后的日子。** 提示词放行之后这次操作就结束了，那个 agent 归
//     [Config.Owner] 那个作用域管，和任何别的会话一样。
//   - **不做规则的调度、限流、重试。** 一条投递匹配几条规则就同时起几个 goroutine。
//   - **不定义规则怎么被配出来。** [Rule] 是同进程里的受信任代码，不是一份能被外部
//     写入的配置。
