// Package repeattoolreminder 认出「同一个工具、同一份参数、连着调」这件事，
// 在到达设定的次数时给模型捎一句提醒。
//
// 对应 DSH 的 @deepseek-ai/dsh-repeat-tool-reminder（packages/guard/repeat-tool-reminder）。
//
// 源: packages/guard/repeat-tool-reminder/src/index.ts:1-8
//
// # 它是**劝告**，不是闸门
//
// 这一层从不拦下任何调用，也从不改写任何结果。它只做一件事：往这次调用的
// [github.com/snight1983/ds-harness-go/tools.PostDecision.AdditionalContexts] 前面插一条消息。
// 拦不拦、换不换，全由别的层决定——所以它装在哪个位置、和谁并排，都不影响别人。
//
// 这个克制是有理由的。「连着调同一个工具」并不总是错的：一次分页遍历、一次轮询、
// 一次按顺序写十个文件，看起来都像重复。真正的死循环和这些在**调用序列**上分不开，
// 只有模型自己看得出区别。所以这一层把事实摆给模型，让它自己判断。
//
// # 为什么计数落在执行**后**
//
// 因为被拒绝的调用也会走到执行后这条瀑布上——一个反复撞同一道拒绝的模型，
// 正是最值得打断的那种循环。计在执行前的话，被守卫挡掉的那些就一次都数不着。
//
// 而且计数在调 next 之**前**就完成：链的状态只取决于「模型又调了一次」，
// 和后面那些层最终怎么裁决无关。
//
// # 什么会把链断掉
//
// 三件事：换了工具、换了参数、用户插了话。
//
// 前两件由 [Reminder.Observe] 自己认；第三件要靠 agent 循环在每一步之前叫一下
// [Reminder.NoticeStep]。用户插话之后上下文已经不同了，跨过它的重复不是循环。
//
// 新增: DSH 把第三件挂在 cordis 的 `agent/pre-step` 事件上。Go 这一侧 harness/agent
// 还没落地，所以「什么算用户插话」这个**判断**留在本包（就是 NoticeStep 的函数体），
// 只有「什么时候叫它」这根线要等循环那一层接上去。判断和接线分开，是为了让这条
// 规则在循环写好之前就能被完整地测到。
//
// # 没被跟踪的工具是**透明**的
//
// Include / Exclude 筛掉的工具既不计数，也不断链。这是有意的：一次 `todo_write`
// 夹在两次同样的 `bash` 中间，那两次 `bash` 仍然是连着的两次。把没跟踪的调用
// 当成断点，等于让模型多插一个无关工具就能把这层甩掉。
//
// # 不做什么
//
//   - **不拦调用，也不改结果。**它只往 [github.com/snight1983/ds-harness-go/tools.PostDecision.AdditionalContexts]
//     前面插一条消息；拦不拦、换不换全由别的层决定，所以它装在哪个位置都不影响别人。
//   - **不判断这次重复是不是错的。**分页遍历、轮询、按顺序写十个文件都长得像重复，
//     真正的死循环只有模型自己看得出区别——这一层把事实摆出来就收手。
//   - **不保证模型停下来。**这是劝告不是闸门；要真的挡住一次调用，得靠工具管线上
//     那些会拒绝的层。
//   - **不自己知道用户插了话。**断链那一下要靠 agent 循环在每一步之前叫
//     [Reminder.NoticeStep]，「什么时候叫」这根线不在本包。
//   - **不干预没被跟踪的工具。**Include / Exclude 筛掉的既不计数也不断链——
//     把它们当成断点，等于给模型留一个多插一个无关工具就能甩掉这层的口子。
