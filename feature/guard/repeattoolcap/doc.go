// Package repeattoolcap 给「同一个工具连着调」设一个次数上限，到顶就拒绝派发。
//
// 新增: DSH 没有这一层。它那边只有 @deepseek-ai/dsh-repeat-tool-reminder，而那一层
// 是劝告——见 [github.com/snight1983/ds-harness-go/feature/guard/repeattoolreminder]
// 包文档里「它是**劝告**，不是闸门」那一节。劝告拦不住一个不听劝的模型，而
// [github.com/snight1983/ds-harness-go/harness/agentloop] 的回合循环没有步数上限：
// 它只在模型这一步不再发工具调用时收场。两件事凑在一起，一个打转的模型可以一直调下去，
// 唯一的边界是上下文被撑爆或者撞 max-tokens——那是事故，不是刹车。这一层就是那道刹车。
//
// # 它是**闸门**，不是劝告
//
// 到顶那一次调用不会被派发，工具的执行体一行都不跑。模型收到的是一份失败结果，
// 内容是一句说明：这个工具已经连着调了几次，别再调了。
//
// 这和 repeattoolreminder 是两件事，可以并存也该并存：那一层认「同名**同参**」，
// 语气是劝，目的是让模型自己发现它在原地打转；这一层认「同名」，语气是拦，
// 目的是保证它停得下来。前者精确但拦不住，后者粗但一定生效。
//
// # 为什么只认工具名，不认参数
//
// 因为要挡的正是那种「每次换一点参数、看起来像有进展」的打转。认参数的话，
// 模型只要在参数里加一个空格就能把这一层甩掉——而那恰好是打转时最常发生的事。
//
// 代价是**会误伤合法的连续调用**：分页遍历、轮询、按顺序写十个文件，都是同一个工具
// 连着调很多次。所以这一层默认什么都不限，上限必须显式配出来；给一个会误伤的默认值，
// 等于让每个接入方都先踩一次坑。
//
// # 什么会把计数清零
//
// 两件事：换了**另一个配了上限的**工具、用户插了话。
//
// 前者由 [Cap.Observe] 自己认；后者由 [Cap.NoticeStep] 认，它挂在 agent 循环
// 每步之前那条瀑布上。用户插话之后上下文已经不同了，跨过它的重复不是打转。
//
// **没配上限的工具是透明的**：它既不计数，也不清零。这是有意的——把它当成断点，
// 等于给模型留一个「两次之间插一次 todo_write 就能甩掉这道闸」的口子，而闸门
// 一旦能被这么便宜地绕过去就等于没有。代价是这里数的「连续」比字面意思宽：
// 中间隔着多少次没配上限的调用都不算断。要让某个工具能断链，就给它也配一个上限。
//
// **没有「结果不一样就清零」这一条。**一次成功和一次失败在这一层眼里没有区别——
// 判断这次结果算不算进展是模型的事，这一层只数次数。
//
// # 为什么计数落在执行**前**
//
// 因为它要在派发之前就能拒绝。这和 repeattoolreminder 落在执行后是相反的取舍，
// 理由也相反：那一层要数得着被别人拒掉的调用，这一层自己就是拒的那个。
//
// 被本层拒掉的调用**照样计数**（先计数，再判断）。所以撞了上限之后计数会继续涨，
// 一直到清零为止——这是有意的：一个反复撞同一道拒绝的模型，不该因为撞得多了反而被放行。
//
// # 不做什么
//
//   - **不改结果，也不挂上下文。**它只在派发之前给一个
//     [github.com/snight1983/ds-harness-go/tools.PreDeny]，理由那句话就是模型看到的全部。
//   - **不给默认上限。**没配到的工具一次都不限。理由见上面「为什么只认工具名」。
//   - **不管一个回合总共调了多少次工具。**它数的是**连续**，中间插一个同样配了
//     上限的工具就清零。要管总量得另设一层。
//   - **不自己知道用户插了话。**那一下靠 [Cap.InstallStepNotice] 接到 agent 循环上。
