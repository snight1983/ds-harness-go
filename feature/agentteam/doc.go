// Package agentteam 是一个队长会话带着一群队友干活的那套东西：一份花名册、
// 一块共享任务板、一条队友之间的收件箱。
//
// 源: packages/experimental/agent-team/src/index.ts
//
// 一支团队没有单独的创建动作。一个会话起出第一个队友的那一刻就成了队长，
// 团队的身份就是队长会话的身份（[TeamID]）——所以「哪支团队」这个问题永远有答案，
// 不必先建一个容器再往里放人。
//
// # 状态在介质上，不是折日志折出来的
//
// 这是本包和 DSH 最大的一处分歧。DSH 那边团队状态是从队长那条会话日志里折出来的
// 一份内存投影，改一次状态就是往队长日志里追一条事件；本包把它落成三张表
// （[RosterTable]、[BoardTable]、[MessageTable]），见 [Spec]。
//
// 换的理由只有一条：**这个模块要能多副本部署**。折日志那套要求所有改动都经过
// 队长那一个活对象，于是整支团队被钉在队长所在的那台机器上。落到介质上之后，
// 认领一条任务、给队友发一条消息，都是对一把键的一次条件写，谁在哪台机器上都做得了。
//
// 代价是三件事：状态不再随日志一起分叉；一支团队的板越大越容易撞条件写
// （[CodeBoardContended]）；「这个队友活着吗」变成了一个只对本副本成立的问题
// （[MemberStatus]、[Agents]）。
//
// # 整块板是一条记录
//
// 改一条任务往往要同时看它的邻居——认领要看前置做完没有，删除要看谁还挡在它后面，
// 设置前置要把整张图重新验一遍（[ValidateGraph]）。
// [github.com/snight1983/ds-harness-go/storage/domain] 不提供跨记录事务，
// 所以整块板收进一条记录，一次条件写就是一次原子改动，跨任务的原子性白拿。
// 完整的取舍写在 [Board] 上。
//
// # 队友就是可续子 Agent
//
// 本包不另起一套会话生命周期。[Service.Spawn] 走的是
// [github.com/snight1983/ds-harness-go/feature/subagent] 那条可续路，
// 花名册上那一行只是给这个子会话安一个团队内的名字和职责。
//
// 起一个队友分两步落盘，中间才去起会话：先占名字写 [PhaseProvisioning]，
// 起成了转 [PhaseActive]，起不成转 [PhaseFailed]。反过来先起会话再落盘的话，
// 一个半开的子会话不会在任何地方留下痕迹。
//
// # 消息承诺至少一次
//
// 一条消息在 [MessageQueued]、[MessageClaimed]、[MessageDelivered] 三档之间走。
// 中间那一档是本包新加的：多副本下两台机器可能同时抓起同一条消息去送，所以「谁正在送」
// 必须落盘。抓着它的副本可能整个消失，于是这一档带一个时刻，
// 过了 [Config.ClaimTTL] 别人就能捡回来重送。
//
// 想要恰好一次，就得让「送到收件人」和「记下送到了」在同一个事务里，
// 而收件人可能在另一台机器上。所以这里承诺的是至少一次，见 [Message]。
//
// # 装配
//
// [Open] 要三样东西：一个域设施、一套子 Agent 能力（[Subagents]）、
// 一个「这个会话此刻在不在本副本上」的查询面（[Agents]）。后两个都是**在使用方声明的
// 窄接口**，[github.com/snight1983/ds-harness-go/feature/subagent.Runtime] 天然满足前者。
//
// 一个队友在本副本上活起来之后，装配方要叫一次 [Service.Deliver]：
// 别的副本看不见这个收件人，也就送不动它那几条压着的消息。
//
// # 不做什么
//
//   - **不面向模型，也不面向人。**这里只有服务；把这些动作包成工具或者命令是别的包的事。
//   - **不管队友的寿命。**队友是可续子 Agent，起来之后归
//     [github.com/snight1983/ds-harness-go/feature/subagent] 管；[Service.Close] 关的是域，
//     一个队友都不停。
//   - **不替业务判断任务做没做完。**状态跃迁合不合法它验，活儿干没干好它不知道；
//     `completed` 是一条被写下来的声明，不是一次验收。
//   - **不拦写入范围冲突。**[TaskView.ScopeWarnings] 只是说给模型听的提醒，
//     它不挡任何一次改动——本包不知道那些范围指的是什么，也没有能力去锁它们。
//   - **不做分布式锁。**并发只有两条防线：任务上的 [Task.Rev]
//     （对不上报 [CodeTaskStaleRevision]）和整块板的条件写（撞穿报 [CodeBoardContended]）。
//   - **不承诺消息恰好一次**，也不保证跨收件人的全局次序。[Service.Deliver] 按排队时刻送，
//     那只在同一个收件人那几条之间有意义。
//   - **不自己去捡掉队的消息。**没有后台清扫线程；[Service.Deliver] 由装配方在收件人
//     活起来时叫，捡回过期认领是顺带发生的。
